#!/usr/bin/env python3
"""Regenerates the simple case folding table (docs/lists.md section 10, #37) and its corpus.

A development tool, not part of the product: the product reads the generated files only. It writes
  crates/cancho-ui-ir/src/casefold_table.rs   (the ranges, as Rust; the emitted JavaScript is built from the same ranges)
  tests/fold_corpus.json                      (hand-picked cases + a digest over every code point, from this script)
Usage: python3 -I scripts/gen_casefold.py   (from the repository root)

Simple case folding (Unicode CaseFolding.txt, statuses C and S): one code point to one code point. Python has only the
full folding (`str.casefold`, status F: "ß" -> "ss"), so the simple fold is derived: the full fold if it is one code point,
else the lowercase mapping if that is one code point and differs, else the character itself. That reproduces the C and S
lines (checked below against the cases the standard names: U+1E9E, U+1F88, U+13F8, U+03C2, U+0130, U+10400).
"""
import json
import unicodedata


def simple_fold(c):
    full = c.casefold()
    if len(full) == 1:
        return full
    low = c.lower()
    if len(low) == 1 and low != c:
        return low
    return c


def table():
    m = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        r = ord(simple_fold(chr(cp)))
        if r != cp:
            m[cp] = r
    return m


def ranges(m):
    """Greedy runs (lo, hi, delta, stride): every lo, lo+stride, ... hi folds to itself plus delta."""
    cps = sorted(m)
    out = []
    i = 0
    while i < len(cps):
        lo = cps[i]
        delta = m[lo] - lo
        stride = 1
        j = i
        if i + 1 < len(cps) and m[cps[i + 1]] - cps[i + 1] == delta:
            stride = cps[i + 1] - lo
        # extend while the next code point continues the run
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + stride and m[cps[j + 1]] - cps[j + 1] == delta:
            j += 1
        out.append((lo, cps[j], delta, stride))
        i = j + 1
    return out


def check_runs(m, rs):
    back = {}
    for lo, hi, d, s in rs:
        for cp in range(lo, hi + 1, s):
            assert cp not in back
            back[cp] = cp + d
    assert back == m


def fnv_digest(m):
    """FNV-1a over fold(cp) for every code point 0..0x10FFFF except the surrogates (32-bit)."""
    h = 2166136261
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        v = m.get(cp, cp)
        h = ((h ^ v) * 16777619) & 0xFFFFFFFF
    return h


NAMED = {0x1E9E: 0xDF, 0x1F88: 0x1F80, 0x13F8: 0x13F0, 0x3C2: 0x3C3, 0x10400: 0x10428, 0x1C80: 0x432}


def main():
    m = table()
    rs = ranges(m)
    check_runs(m, rs)
    for cp, want in NAMED.items():
        assert m[cp] == want, hex(cp)
    for cp in (0x130, 0x131, 0xDF, 0x390):
        assert cp not in m, hex(cp)
    version = unicodedata.unidata_version
    lines = [
        "// GENERATED by scripts/gen_casefold.py -- do not edit. Simple case folding (CaseFolding.txt statuses C and S),",
        f"// Unicode {version} as shipped in Python's unicodedata, {len(m)} code points in {len(rs)} runs.",
        "",
        f'pub const UNICODE_VERSION: &str = "{version}";',
        "",
        "/// (first, last, delta, stride): every `first`, `first + stride`, .. `last` folds to itself plus `delta`.",
        f"pub const FOLD_RANGES: [(u32, u32, i32, u32); {len(rs)}] = [",
    ]
    for lo, hi, d, s in rs:
        lines.append(f"    (0x{lo:X}, 0x{hi:X}, {d}, {s}),")
    lines.append("];")
    open("crates/cancho-ui-ir/src/casefold_table.rs", "w").write("\n".join(lines) + "\n")

    def f(t):
        return "".join(chr(m.get(ord(c), ord(c))) for c in t)

    cases = [
        ("an empty text", ""),
        ("ASCII letters", "Hello, World 123"),
        ("German name with an umlaut", "Pumpe Ünit"),
        ("the same name in lower case", "pumpe ünit"),
        ("the eszett stays (simple folding, not full)", "Straße"),
        ("capital sharp s folds to the eszett", "STRAẞE"),
        ("Greek capital sigma", "ΣΑΣ"),
        ("Greek final sigma folds to sigma", "σας"),
        ("Turkish dotted capital I is unchanged", "İstanbul"),
        ("Turkish dotless i is unchanged", "ışık"),
        ("ASCII I folds to i whatever the language", "ISTANBUL"),
        ("Cyrillic", "Москва"),
        ("Armenian", "ԱԲԳ"),
        ("Cherokee small letters fold to capitals", "ᏸᏹ"),
        ("an astral letter (Deseret)", "\U00010400\U00010428"),
        ("a title-case digraph (Dz)", "ǅ"),
        ("Greek with a title-case iota subscript (simple)", "ᾈ"),
        ("combining mark and a symbol are untouched", "é ☃"),
        ("an emoji is untouched", "a\U0001f600B"),
        ("fold is idempotent on text already folded", "straße ü σ"),
    ]
    out = {
        "why": "fold(text) (docs/lists.md section 10): simple case folding from one table, shared by replay (cargo test, tests/lists.rs) and the emitted __cui_fold (scripts/check-lists.js). Generated by scripts/gen_casefold.py.",
        "unicode": version,
        "cases": [{"why": w, "text": t, "fold": f(t)} for w, t in cases],
        "equal": [
            ["ÜNIT", "ünit"],
            ["ΣΑΣ", "σας"],
            ["STRAẞE", "straße"],
            ["МОСКВА", "москва"],
        ],
        "different": [
            ["İ", "i"],
            ["ı", "i"],
            ["ß", "ss"],
            ["a", "b"],
        ],
        "all_code_points": {"count": 0x110000 - 0x800, "fnv1a32": fnv_digest(m), "changed": len(m)},
    }
    json.dump(out, open("tests/fold_corpus.json", "w"), indent=1, ensure_ascii=False)
    open("tests/fold_corpus.json", "a").write("\n")
    print(len(m), "code points,", len(rs), "runs, unicode", version, "digest", fnv_digest(m))


main()
