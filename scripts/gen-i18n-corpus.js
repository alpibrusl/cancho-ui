#!/usr/bin/env node
// Writes tests/i18n_corpus.json (docs/i18n.md section 4): inputs for fmt.number, fmt.percent, fmt.date, fmt.time and the plural rules, with
// what Chromium's `Intl` answers for each. The file is read by `cargo test` (replay's formatting, in Rust) and by scripts/check-i18n.js
// (the page's formatting, in JavaScript): the two implementations are checked against the same oracle and not against each other.
//   node scripts/gen-i18n-corpus.js
'use strict';
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
setTimeout(() => { console.error('FAIL the generator took more than 2 minutes'); process.exit(1); }, 120000).unref();

const LANGS = ['en', 'es', 'de', 'fr', 'pt', 'ru', 'ar', 'he', 'ja', 'hi'];
let seed = 82;
const rnd = () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x7fffffff; };
const numbers = [0, 1, 0.5, 1.005, 2.5, 1234.5, 999999.5, 1e6, 0.145, 0.07, -0.001, -1234567.891, 123456789.123456, 1e20, 99.995, 0.000001, 12345, 1234, 999, 1000, 10000, 100000, 0.1 + 0.2, 1 / 3, 2 / 3, -2.5, 4.35, 1e15 + 0.5, 12345678];
for (let i = 0; i < 40; i++) { const mag = 10 ** Math.floor(rnd() * 12 - 3); numbers.push(Number(((rnd() - 0.2) * mag).toPrecision(1 + Math.floor(rnd() * 12)))); }
// a value under 1e-6 in size is written as zero by the language (docs/i18n.md section 3.3), which Intl does not: leave those out
for (let i = numbers.length - 1; i >= 0; i--) { if (numbers[i] !== 0 && Math.abs(numbers[i]) < 1e-6) { numbers.splice(i, 1); } }
const U = (y, m, d, h = 0, mi = 0, s = 0, ms = 0) => Date.UTC(y, m, d, h, mi, s, ms);
const dates = [U(2026, 9, 24, 15, 5, 9), U(2026, 0, 5, 9, 5), U(1000, 0, 1), U(9999, 11, 31, 23, 59, 59, 999), U(2024, 1, 29, 12, 0), U(2026, 11, 31, 0, 0), U(2000, 0, 1, 0, 0), U(1970, 0, 1), U(1969, 11, 31, 23, 59, 59, 999), U(1900, 2, 1, 6, 30), U(2100, 1, 28, 18, 45), U(1582, 9, 15, 11, 11), U(2026, 5, 15, 12, 59), U(2026, 5, 15, 13, 0), U(2026, 2, 8, 0, 5), -1.5, -0.5, -86400000.5, 1e12 + 0.7, 86399999.5];
for (let i = 0; i < 25; i++) { dates.push(Math.floor(U(1001, 0, 1) + rnd() * (U(9998, 0, 1) - U(1001, 0, 1)))); }
// whole counts only: CLDR gives `one` to 1.5 in French, Portuguese and Hindi; the language models whole counts and calls the rest `other` (docs/i18n.md)
const counts = Array.from({ length: 112 }, (_, i) => i).concat([200, 999, 1000, 1001, 1002, 1011, 1111, 100000, 1000000, 2000000, 1000001, 1e9, 1e12, -1]);

function oracle(LANGS, numbers, dates, counts) {
  const out = { numbers: [], percents: [], dates: [], times: [], plurals: {} };
  for (const l of LANGS) {
    for (const x of numbers) {
      for (const d of [0, 2, 3]) {
        out.numbers.push({ lang: l, x, digits: d, want: new Intl.NumberFormat(l, { minimumFractionDigits: d, maximumFractionDigits: d }).format(x) });
      }
      out.percents.push({ lang: l, x, want: new Intl.NumberFormat(l, { style: 'percent', maximumFractionDigits: 0 }).format(x) });
    }
    for (const ms of dates) {
      for (const style of ['short', 'medium', 'long', 'full']) {
        out.dates.push({ lang: l, ms, style, want: new Intl.DateTimeFormat(l, { dateStyle: style, timeZone: 'UTC' }).format(ms) });
      }
      out.times.push({ lang: l, ms, want: new Intl.DateTimeFormat(l, { timeStyle: 'short', timeZone: 'UTC' }).format(ms) });
    }
    const pr = new Intl.PluralRules(l);
    out.plurals[l] = counts.map((n) => pr.select(n));
  }
  return out;
}

(async () => {
  const browser = await chromium.launch({ args: ['--no-proxy-server'] });
  const page = await browser.newPage();
  await page.goto('about:blank');
  const o = await page.evaluate(`(${oracle.toString()})(${JSON.stringify(LANGS)}, ${JSON.stringify(numbers)}, ${JSON.stringify(dates)}, ${JSON.stringify(counts)})`);
  const version = browser.version();
  await browser.close();
  // the cases the language leaves out on purpose (docs/i18n.md section 3.3): under 1e-6 is zero, and 1e21 and over is ""
  const file = { note: `Generated by scripts/gen-i18n-corpus.js from Chromium ${version}'s Intl. 'want' is what Intl answers; do not edit by hand.`, chromium: version, counts, ...o };
  fs.writeFileSync(path.join(__dirname, '..', 'tests', 'i18n_corpus.json'), JSON.stringify(file));
  console.log(`wrote tests/i18n_corpus.json: ${o.numbers.length} numbers, ${o.percents.length} percents, ${o.dates.length} dates, ${o.times.length} times, ${Object.keys(o.plurals).length} plural lists`);
})().catch((e) => { console.error(e); process.exit(1); });
