//! The web backend's emitter for Tier 2: state, events, reactive
//! re-render, the `Button` primitive, and string interpolation.
//!
//! ## Reactive model
//!
//! Each component has a single `mount_<Name>(root)` function. State
//! is held in plain `let` variables inside an IIFE so that closures
//! (event handlers) capture them by reference. An event handler
//! updates state and calls `__render()` which:
//!
//! 1. Builds a new view tree by re-evaluating the view block
//!    against the current state.
//! 2. Creates a fresh DOM subtree.
//! 3. Replaces the existing root's children with the new subtree.
//!
//! This is coarse-grained reactivity — every state change
//! re-renders the entire component. The language semantics are the
//! same as fine-grained reactivity; only the implementation
//! differs. Phase 3 may swap this for fine-grained without changing
//! the IR.

use cancho_ui_ir::ir::*;

pub fn module_for_file(ir: &IrFile) -> String {
    emit_module(ir, None)
}

pub fn emit_module(ir: &IrFile, source_name: Option<&str>) -> String {
    let mut out = String::new();
    out.push_str("// Generated by cancho-ui build (Tier 4, web backend).\n");
    if let Some(name) = source_name {
        out.push_str("// Source: ");
        out.push_str(name);
        out.push('\n');
    }
    out.push_str("// Schema: ");
    out.push_str(&ir.schema);
    out.push(' ');
    out.push_str(&ir.version);
    out.push('\n');
    out.push_str("//\n");
    out.push_str("// Do not edit by hand. Re-run `cancho-ui build` to regenerate.\n");
    out.push('\n');

    // Platform adapters: thin wrappers over browser APIs. Phase 2
    // will move these into separately-imported cancho-ui source
    // files (the "platform adapter" example in the proposal). For
    // Tier 4 we emit them inline so the binary is self-contained.
    let mut any_clock = false;
    let mut any_sleep = false;
    let mut any_network = false;
    let mut any_net_get = false;
    let mut any_location = false;
    let mut any_storage = false;
    let mut any_cancel = false;
    for c in &ir.components {
        for e in &c.reachable_effects {
            if e.capability == "Clock" {
                any_clock = true;
            }
            if e.capability == "Network" && e.path.last().is_some_and(|f| f == "get") {
                any_net_get = true;
            } else if e.capability == "Network" {
                any_network = true;
            }
            if e.capability == "Storage" {
                any_storage = true;
            }
            if e.capability == "Location" {
                any_location = true;
            }
        }
        for arm in c.events.iter().flat_map(|e| e.body.iter()) {
            if body_uses_await(arm) || body_uses_sleep(arm) {
                any_sleep = true;
            }
        }
        if view_node_uses_await_or_sleep(&c.view.body) {
            any_sleep = true;
        }
        // Tier 10: any `await(...)` anywhere needs the
        // cancellation runtime (`__cui_call`, sentinel).
        if c.events.iter().any(|e| e.body.iter().any(body_uses_await))
            || view_node_uses_await_or_sleep(&c.view.body)
        {
            any_cancel = true;
        }
    }
    if any_clock {
        out.push_str(CLOCK_ADAPTER_JS);
        out.push('\n');
    }
    if any_storage {
        out.push_str(STORAGE_ADAPTER_JS);
        out.push('\n');
    }
    if any_sleep {
        out.push_str(SLEEP_ADAPTER_JS);
        out.push('\n');
    }
    if any_network {
        out.push_str(NETWORK_ADAPTER_JS);
        out.push('\n');
    }
    if any_net_get {
        out.push_str(NET_GET_ADAPTER_JS);
        out.push('\n');
    }
    if any_location {
        out.push_str(LOCATION_ADAPTER_JS);
        out.push('\n');
    }
    if any_cancel {
        out.push_str(CANCEL_ADAPTER_JS);
        out.push('\n');
    }
    // A control the user is using must keep focus across the rebuild a state change causes.
    let keep_focus = ir
        .components
        .iter()
        .any(|c| view_has_focusable(&c.view.body));
    if keep_focus {
        out.push_str(FOCUS_ADAPTER_JS);
        out.push('\n');
    }

    // Tier 13: components some instance passes a property to get
    // the `props`-aware mount signature.
    let mut prop_consumers: Vec<String> = Vec::new();
    for c in &ir.components {
        collect_prop_consumers(&c.view.body, &mut prop_consumers);
    }

    let component_names: Vec<String> = ir.components.iter().map(|c| c.name.clone()).collect();
    for c in &ir.components {
        out.push_str(&emit_component(
            c,
            &component_names,
            &prop_consumers,
            keep_focus,
        ));
        out.push('\n');
    }

    if let Some(last) = ir.components.last() {
        out.push_str("const root = (typeof document !== 'undefined') ? document.getElementById('root') : null;\n");
        out.push_str("if (root) { mount_");
        out.push_str(&last.name);
        out.push_str("(root); }\n");
        out.push_str("export { mount_");
        out.push_str(&last.name);
        out.push_str(" };\n");
    }

    out
}

/// The `Storage` adapter (docs/adapters.md): a string-to-string store under the key prefix `cui:` in
/// `localStorage`, with a page-lifetime fallback when `localStorage` is absent or throws (a private window,
/// blocked site data, a full quota). `set` answers whether the value is persisted.
const STORAGE_ADAPTER_JS: &str = "\
// Platform adapter: Storage capability (docs/adapters.md).
// Keys live under the prefix `cui:` in localStorage, or `cui:<ns>:` for a component that declares
// `requires Storage(\"ns\")`; a program cannot read or write any other key. When localStorage is
// unavailable the store lasts as long as the page, and `storage.set` answers false.
var __cui_storage_memory = {};
function __cui_storage_get(key, fallback, ns) {
    var k = 'cui:' + (ns ? ns + ':' : '') + String(key);
    try {
        var v = window.localStorage.getItem(k);
        if (v !== null) { return v; }
    } catch (e) { /* unavailable: fall through to memory */ }
    return Object.prototype.hasOwnProperty.call(__cui_storage_memory, k) ? __cui_storage_memory[k] : fallback;
}
function __cui_storage_set(key, value, ns) {
    var k = 'cui:' + (ns ? ns + ':' : '') + String(key);
    try {
        window.localStorage.setItem(k, String(value));
        delete __cui_storage_memory[k];
        return true;
    } catch (e) {
        __cui_storage_memory[k] = String(value);
        return false;
    }
}
";

const CLOCK_ADAPTER_JS: &str = "\
// Platform adapter: Clock capability (Tier 4 stub).
// Phase 2 will replace this with an imported cancho-ui source file
// that wraps `Date.now()` in a typed boundary.
function __cui_clock_now() {
    return Date.now();
}
";

/// Does a view hold a control the user can focus (a `Button` or a `TextField`), directly or in a `For`?
fn view_has_focusable(node: &IrViewNode) -> bool {
    match node {
        IrViewNode::Element { kind, children, .. } => {
            matches!(kind, IrElementKind::Button | IrElementKind::TextField)
                || children.iter().any(view_has_focusable)
        }
        IrViewNode::For { children, .. } => children.iter().any(view_has_focusable),
        IrViewNode::Text { .. } => false,
    }
}

/// Focus survives a re-render. A view is rebuilt from scratch on every state change, so the control the user is
/// using was replaced and focus fell to the page: typing "ada" into a `TextField` left "a", and pressing Enter three
/// times on a focused `Button` counted once (both measured).
/// Before the rebuild the focused control's place under this component's root (its path of child indices) and its
/// text selection are recorded; after it, the control at that path gets both back. A control that is gone, or is a
/// different kind or has another label, stays unfocused rather than focusing the wrong one. Not handled: an
/// input method composition in progress.
const FOCUS_ADAPTER_JS: &str = r#"// Focus survives a re-render: see docs/semantics.md, Question 9.
function __cui_focus_save(root) {
    const el = document.activeElement;
    if (!el || el === document.body || el === root || !root.contains(el)) { return null; }
    const path = [];
    for (let n = el; n !== root; n = n.parentNode) {
        path.unshift(Array.prototype.indexOf.call(n.parentNode.childNodes, n));
    }
    return {
        path: path,
        tag: el.tagName,
        label: el.getAttribute('aria-label'),
        start: el.selectionStart,
        end: el.selectionEnd,
        direction: el.selectionDirection,
    };
}
function __cui_focus_restore(root, saved) {
    if (!saved) { return; }
    let n = root;
    for (let i = 0; i < saved.path.length && n; i++) { n = n.childNodes[saved.path[i]]; }
    if (!n || n.tagName !== saved.tag || n.getAttribute('aria-label') !== saved.label) { return; }
    n.focus();
    if (typeof saved.start === 'number' && n.setSelectionRange) {
        try { n.setSelectionRange(saved.start, saved.end, saved.direction); } catch (e) { /* not a text control */ }
    }
}
"#;

const SLEEP_ADAPTER_JS: &str = "\
// Platform adapter: async sleep (Tier 7).
// `sleep(ms)` returns a Promise that resolves to
// `{__cui_tag: \"Ok\", value: undefined}` after `ms` milliseconds.
// The `await(...)` expression in cancho-ui lowers to `await expr`
// in JS, so the resolved value flows into the surrounding
// statement. Tier 7 does not implement cancellation yet — the
// `Cancelled` variant is matched but never produced.
function __cui_sleep_ms(ms) {
    return new Promise(function (resolve) {
        setTimeout(function () { resolve({__cui_tag: \"Ok\", value: undefined}); }, ms);
    });
}
";

const NETWORK_ADAPTER_JS: &str = "\
// Platform adapter: Network capability (Tier 9).
// `net.search(q)` returns a Promise that resolves to
// `{__cui_tag: \"Ok\", value: [...]}` after a simulated network
// delay. Tier 9 stub: the search filters a fixed corpus by
// substring, so the demo is fully interactive offline. The delay
// grows with the query length so slow requests demonstrably
// return AFTER fast ones — which is exactly what Tier 10
// cancellation protects against. A failing deadline resolves
// with `{__cui_tag: \"Err\", reason}` instead.
const __CUI_CORPUS = [
    \"Ada Lovelace\", \"Grace Hopper\", \"Linus Torvalds\",
    \"Andrey Kolmogorov\", \"Bertrand Russell\", \"Ada Marrero\",
];
function __cui_net_search(q) {
    return new Promise(function (resolve) {
        setTimeout(function () {
            const needle = String(q).trim().toLowerCase();
            const value = __CUI_CORPUS.filter(function (item) {
                return item.toLowerCase().indexOf(needle) !== -1;
            });
            resolve({__cui_tag: \"Ok\", value: value});
        }, 60 + 45 * String(q).length);
    });
}
";

/// The `net.get` adapter (docs/adapters.md section 9): a same-origin GET with a size bound and a deadline.
const NET_GET_ADAPTER_JS: &str = "\
// Platform adapter: Network capability, `net.get(url)` (docs/adapters.md section 9).
// A GET of this page's own origin, or of a host the component's `requires Network(\"host\")` names: any other
// URL is answered with Err before a request is made, a redirect is refused (it could leave the allowed set), a
// body over 1 MiB or a reply later than 10 s is an Err, and every failure is a value, never a throw.
function __cui_net_get(url, hosts) {
    var err = function (reason) { return {__cui_tag: \"Err\", reason: reason}; };
    return new Promise(function (resolve) {
        var target;
        try {
            target = new URL(String(url), window.location.href);
        } catch (e) {
            resolve(err(\"blocked: not a URL\"));
            return;
        }
        if (target.protocol !== \"http:\" && target.protocol !== \"https:\") {
            resolve(err(\"blocked: not an http(s) URL\"));
            return;
        }
        if (target.origin !== window.location.origin && hosts.indexOf(target.host.toLowerCase()) === -1) {
            resolve(err(\"blocked: \" + target.host + \" is neither this site nor an allowed host\"));
            return;
        }
        var timer = null;
        var controller = typeof AbortController === \"function\" ? new AbortController() : null;
        if (controller) { timer = setTimeout(function () { controller.abort(); }, 10000); }
        var init = { method: \"GET\", credentials: \"same-origin\", redirect: \"manual\" };
        if (controller) { init.signal = controller.signal; }
        fetch(target.href, init).then(function (response) {
            if (response.type === \"opaqueredirect\") { return err(\"blocked: redirect\"); }
            if (!response.ok) { return err(\"HTTP \" + response.status); }
            return response.text().then(function (text) {
                return text.length > 1048576 ? err(\"too large\") : {__cui_tag: \"Ok\", value: text};
            });
        }).catch(function (e) {
            return err(e && e.name === \"AbortError\" ? \"timeout\" : \"network error\");
        }).then(function (result) {
            if (timer !== null) { clearTimeout(timer); }
            resolve(result);
        });
    });
}
";

/// The `location.current` adapter (docs/adapters.md section 11): the browser's Geolocation, rounded in the adapter.
const LOCATION_ADAPTER_JS: &str = "\
// Platform adapter: Location capability, `location.current()` (docs/adapters.md section 11).
// Resolves to \"lat,lon\" in decimal degrees, rounded to `digits` decimals (2, about 1 km, unless the component
// asked for \"fine\": 5). The browser asks the user; a refusal, a timeout or a missing API is an Err value.
function __cui_location_current(digits) {
    var err = function (reason) { return {__cui_tag: \"Err\", reason: reason}; };
    return new Promise(function (resolve) {
        if (typeof navigator === \"undefined\" || !navigator.geolocation) {
            resolve(err(\"unavailable\"));
            return;
        }
        try {
            navigator.geolocation.getCurrentPosition(function (pos) {
                resolve({__cui_tag: \"Ok\", value: pos.coords.latitude.toFixed(digits) + \",\" + pos.coords.longitude.toFixed(digits)});
            }, function (e) {
                resolve(err(e && e.code === 1 ? \"permission denied\" : e && e.code === 3 ? \"timeout\" : \"position unavailable\"));
            }, { enableHighAccuracy: digits > 2, timeout: 10000, maximumAge: 60000 });
        } catch (e) {
            resolve(err(\"unavailable\"));
        }
    });
}
";

const CANCEL_ADAPTER_JS: &str = "\
// Platform adapter: runtime cancellation (Tier 10), with per-
// component disposal (Tier 17).
// `await(expr)` lowers to `__cui_call(group, start, inflight)`:
//   - the inflight table is *per component instance*: two
//     components awaiting the same effect never cancel each
//     other's requests;
//   - within one component, starting a call cancels the group's
//     still-pending request (stale-result protection: a newer
//     search supersedes an older one) — a superseded request
//     resolving later throws the `__cui_cancelled` sentinel and
//     the handler's try/catch swallows it: the rest of that
//     handler is *dropped* (drop at the await);
//   - component disposal (a slot removal, or the parent's
//     disposal) marks the pending token `disposed`, and the
//     pending await *resolves* to `{__cui_tag:\"Cancelled\"}` —
//     the `match`'s `Cancelled` arm dispatches. The arm is
//     compile-time mandatory for an awaited field, so a disposed
//     component's handler always has the program's cancellation
//     design to run; it then continues on a detached subtree.
const __cui_cancelled = Symbol(\"__cui_cancelled\");
function __cui_call(group, start, inflight) {
    const prev = inflight[group];
    if (prev) { prev.cancelled = true; }
    const token = { cancelled: false, disposed: false };
    inflight[group] = token;
    return start().then(function (res) {
        if (token.cancelled) { throw __cui_cancelled; }
        if (token.disposed) { return {__cui_tag: \"Cancelled\"}; }
        if (inflight[group] === token) { inflight[group] = null; }
        return res;
    });
}
";

/// Recursive helper: does this statement contain an `await`
/// expression? Used to decide whether to emit the async helper.
fn body_uses_await(s: &IrStmt) -> bool {
    match s {
        IrStmt::Assign { value, .. } => expr_uses_await(value),
        IrStmt::Expr { expr, .. } => expr_uses_await(expr),
    }
}

fn expr_uses_await(e: &IrExpr) -> bool {
    match e {
        IrExpr::Await { .. } => true,
        IrExpr::Binary { lhs, rhs, .. } => expr_uses_await(lhs) || expr_uses_await(rhs),
        IrExpr::Unary { operand, .. } => expr_uses_await(operand),
        IrExpr::Call { args, .. } => args.iter().any(expr_uses_await),
        IrExpr::Ok { value, .. } => expr_uses_await(value),
        IrExpr::Err { reason, .. } => expr_uses_await(reason),
        IrExpr::Match {
            scrutinee, arms, ..
        } => expr_uses_await(scrutinee) || arms.iter().any(|a| expr_uses_await(&a.body)),
        _ => false,
    }
}

/// Recursive helper: does this statement contain a call to
/// `sleep(...)`? Used to decide whether to emit the sleep adapter.
fn body_uses_sleep(s: &IrStmt) -> bool {
    match s {
        IrStmt::Assign { value, .. } => expr_uses_sleep(value),
        IrStmt::Expr { expr, .. } => expr_uses_sleep(expr),
    }
}

fn expr_uses_sleep(e: &IrExpr) -> bool {
    match e {
        IrExpr::Call { path, args, .. } => {
            (path.len() == 1 && path[0] == "sleep") || args.iter().any(expr_uses_sleep)
        }
        IrExpr::Binary { lhs, rhs, .. } => expr_uses_sleep(lhs) || expr_uses_sleep(rhs),
        IrExpr::Unary { operand, .. } => expr_uses_sleep(operand),
        IrExpr::Ok { value, .. } => expr_uses_sleep(value),
        IrExpr::Err { reason, .. } => expr_uses_sleep(reason),
        IrExpr::Match {
            scrutinee, arms, ..
        } => expr_uses_sleep(scrutinee) || arms.iter().any(|a| expr_uses_sleep(&a.body)),
        _ => false,
    }
}

fn view_node_uses_await_or_sleep(node: &IrViewNode) -> bool {
    match node {
        IrViewNode::Element { children, .. } => children.iter().any(view_node_uses_await_or_sleep),
        IrViewNode::Text { parts, .. } => parts.iter().any(|p| match p {
            IrTextPart::Literal(_) => false,
            IrTextPart::Expr(e) => expr_uses_await(e) || expr_uses_sleep(e),
        }),
        IrViewNode::For { over, children, .. } => {
            expr_uses_await(over)
                || expr_uses_sleep(over)
                || children.iter().any(view_node_uses_await_or_sleep)
        }
    }
}

const STATE_PREFIX: &str = "__state_";

/// Tier 13: which components receive properties from some
/// instance? Those get the `props`-aware mount signature.
fn collect_prop_consumers(node: &IrViewNode, out: &mut Vec<String>) {
    match node {
        IrViewNode::Element {
            kind,
            bindings,
            children,
            ..
        } => {
            if let IrElementKind::Named(name) = kind
                && bindings
                    .iter()
                    .any(|b| matches!(b.value, IrBindingValue::Const { .. }))
            {
                out.push(name.clone());
            }
            for c in children {
                collect_prop_consumers(c, out);
            }
        }
        IrViewNode::For { children, .. } => {
            for c in children {
                collect_prop_consumers(c, out);
            }
        }
        IrViewNode::Text { .. } => {}
    }
}

fn emit_component(
    c: &IrComponent,
    component_names: &[String],
    prop_consumers: &[String],
    keep_focus: bool,
) -> String {
    // Tier 13: components that some instance passes properties to
    // take a `props` argument; their state initializers consult
    // it, falling back to the declared default. Components never
    // instantiated with properties keep the plain signature and
    // initializers.
    let takes_props = prop_consumers.contains(&c.name);
    // Tier 15: components whose view instantiates subcomponents
    // carry a slot table — one persistent wrapper per instance
    // site, surviving re-renders so that a child's state survives
    // the parent re-render instead of resetting.
    // Tier 15: does this view subtree contain a component instance?
    let has_instances = view_has_instance(&c.view.body, component_names);
    // Tier 17: does any of this component's code await? Awaiting
    // components get a *per-instance* inflight table (two
    // components with the same effect keep independent groups) and
    // a dispose handle that cancels their pending requests.
    let has_awaits = c.events.iter().any(|e| e.body.iter().any(body_uses_await))
        || view_node_uses_await_or_sleep(&c.view.body);
    let needs_dispose = has_awaits || has_instances;
    let mut out = String::new();
    out.push_str("// Component: ");
    out.push_str(&c.name);
    out.push_str(" (id ");
    out.push_str(&c.id.0.to_string());
    out.push_str(")\n");
    out.push_str("function mount_");
    out.push_str(&c.name);
    if takes_props {
        out.push_str("(root, props) {\n");
    } else {
        out.push_str("(root) {\n");
    }
    out.push_str("    ");
    // Tier 15: a prop-consuming child returns its update handle
    // (the IIFE's result), so the parent's slot can call
    // `__cui_update` on later re-renders. Children that never
    // receive properties return nothing.
    // Tier 17: a component that awaits or hosts instances returns
    // a `__cui_dispose` handle as well — its slot's removal calls
    // it, and its own disposal cascades to its children.
    let returns_handle = takes_props || needs_dispose;
    if returns_handle {
        out.push_str("return ");
    }
    out.push_str("(function () {\n");

    for s in &c.state {
        out.push_str("        let ");
        out.push_str(STATE_PREFIX);
        out.push_str(&s.name);
        out.push_str(" = ");
        if takes_props {
            out.push_str(&format!(
                "(props == null || props.{0} === undefined) ? ({1}) : props.{0}",
                s.name,
                emit_expr_init(&s.initial)
            ));
        } else {
            out.push_str(&emit_expr_init(&s.initial));
        }
        out.push_str(";\n");
    }

    // Tier 15: the slot table lives at mount-function scope so
    // `__render()` can re-attach the same wrapper elements (and
    // with them the mounted children's state). Only components
    // with instance sites in their view pay for it.
    if has_instances {
        out.push_str("        const __cui_slots = { };\n");
    }

    // Tier 17: the per-instance cancellation table. Only an
    // awaiting component carries one; with it, two components
    // awaiting the same effect never cancel each other's requests.
    if has_awaits {
        out.push_str("        const __cui_inflight = { };\n");
    }
    // docs/adapters.md 10: the hosts other than this page's own that `net.get` may reach, from the bounds of
    // `requires Network(..)`, lower-cased. Per instance, so two components keep their own allow-lists.
    if c.requires.iter().any(|r| r.name == "Storage") {
        // docs/adapters.md 12: `requires Storage("ns")` keeps this component's keys under `cui:ns:`;
        // without a bound the keys are under `cui:` as before.
        let ns = c
            .requires
            .iter()
            .filter(|r| r.name == "Storage")
            .find_map(|r| r.bounds.first())
            .map(String::as_str)
            .unwrap_or("");
        out.push_str(&format!("        const __cui_storage_ns = \"{ns}\";\n"));
    }
    if c.requires.iter().any(|r| r.name == "Location") {
        let fine = c
            .requires
            .iter()
            .filter(|r| r.name == "Location")
            .any(|r| r.bounds.iter().any(|b| b == "fine"));
        out.push_str(&format!(
            "        const __cui_location_digits = {};\n",
            if fine { 5 } else { 2 }
        ));
    }
    if c.requires.iter().any(|r| r.name == "Network") {
        let hosts: Vec<String> = c
            .requires
            .iter()
            .filter(|r| r.name == "Network")
            .flat_map(|r| r.bounds.iter())
            .map(|b| format!("\"{}\"", b.to_ascii_lowercase()))
            .collect();
        out.push_str(&format!(
            "        const __cui_net_hosts = [{}];\n",
            hosts.join(", ")
        ));
    }

    for e in &c.events {
        // Event handlers are emitted as `async function` so that
        // `await(...)` can suspend until a `Request[T]` resolves
        // and the rest of the body runs with the resolved value.
        // Handlers that never use `await` pay one microtask
        // (the same cost as a resolved Promise). Tier 7 keeps
        // this uniform; Phase 2 can special-case sync-only
        // handlers.
        out.push_str("        async function __on_");
        out.push_str(&e.name);
        out.push('(');
        out.push_str(&e.params.join(", "));
        out.push_str(") {\n");
        let param_set: Vec<&str> = e.params.iter().map(|s| s.as_str()).collect();
        // If the body awaits, paint the pre-await state first: a
        // loading status set before `await(...)` must reach the
        // DOM while the handler is suspended, so emit a
        // synchronous `__render()` after the statements that
        // precede the first await. (The final `__render()` at the
        // end of the handler repaints the post-resolution state.)
        //
        // The whole body sits in a try/catch that swallows the
        // `__cui_cancelled` sentinel: when a request is
        // superseded, its resolution throws the sentinel out of
        // the awaiting statement and the *rest of the handler*
        // never runs — the stale continuation is dropped, so a
        // slower old request cannot clobber the newer one's
        // state. Other exceptions rethrow.
        let first_await = e.body.iter().position(body_uses_await);
        out.push_str("            try {\n");
        for (i, s) in e.body.iter().enumerate() {
            out.push_str("                ");
            out.push_str(&emit_stmt(s, &param_set));
            out.push('\n');
            if Some(i + 1) == first_await {
                out.push_str("                __render();\n");
            }
        }
        out.push_str("                __render();\n");
        out.push_str("            } catch (e) {\n");
        out.push_str("                if (e !== __cui_cancelled) { throw e; }\n");
        out.push_str("            }\n");
        out.push_str("        }\n");
    }

    out.push_str("        function __render() {\n");
    if keep_focus {
        out.push_str("            const __focus = __cui_focus_save(root);\n");
    }
    out.push_str("            root.textContent = '';\n");
    let mut node_id = 0u32;
    let view_body = emit_view_node(
        &mut node_id,
        "            ",
        &c.view.body,
        "root",
        &[],
        component_names,
        prop_consumers,
        has_instances,
        "\"\"",
        None,
    );
    out.push_str(&view_body);
    if keep_focus {
        out.push_str("            __cui_focus_restore(root, __focus);\n");
    }
    out.push_str("        }\n");

    out.push_str("        __render();\n");

    // Tier 15: prop-consuming components return an update handle.
    // The parent re-render moves a slot wrapper (which keeps the
    // child's whole subtree and closures alive) and then calls
    // `__cui_update` with the *dynamic* property values only — a
    // constant property is an initial value for the field, so a
    // parent re-render must not clobber a field the child has
    // changed since mount.
    // Tier 17: awaiting components also return a `__cui_dispose`
    // handle — the pending awaits resolve `{Cancelled}` so the
    // `match`'s `Cancelled` arm dispatches (drop happens for
    // *supersede*, not disposal).
    if returns_handle {
        let mut fields = String::new();
        if takes_props {
            let mut upd = String::new();
            for s in &c.state {
                upd.push_str(&format!(
                    "                if (props.{0} !== undefined) {{ __state_{0} = props.{0}; }}\n",
                    s.name
                ));
            }
            fields.push_str("            __cui_update: function (props) {\n");
            fields.push_str(&upd);
            fields.push_str("                __render();\n");
            fields.push_str("            }");
        }
        if needs_dispose {
            if !fields.is_empty() {
                fields.push_str(",\n");
            }
            fields.push_str("            __cui_dispose: function () {\n");
            if has_instances {
                // Cascade first: the children of a disposed
                // component are disposed too, transitively (the
                // slot table holds every instance this component
                // mounted; For sites hold arrays of slots).
                fields.push_str("                for (const __dk in __cui_slots) {\n");
                fields.push_str("                    const __ds = __cui_slots[__dk];\n");
                fields.push_str("                    if (Array.isArray(__ds)) {\n");
                fields.push_str("                        __ds.forEach(function (x) { if (x.inst) x.inst.__cui_dispose(); });\n");
                fields.push_str("                    } else if (__ds.inst) {\n");
                fields.push_str("                        __ds.inst.__cui_dispose();\n");
                fields.push_str("                    }\n");
                fields.push_str("                }\n");
            }
            if has_awaits {
                // Then the instance's own pending requests: their
                // awaits resolve `{Cancelled}` and the awaiting
                // `match` dispatches the arm.
                fields.push_str("                for (const g in __cui_inflight) {\n");
                fields.push_str("                    const t = __cui_inflight[g];\n");
                fields.push_str(
                    "                    if (t) { t.disposed = true; __cui_inflight[g] = null; }\n",
                );
                fields.push_str("                }\n");
            }
            fields.push_str("            }");
        }
        out.push_str("        return {\n");
        out.push_str(&fields);
        out.push_str("\n        };\n");
    }
    out.push_str("    })();\n");
    out.push_str("}\n");
    out
}

/// Tier 15: does this view subtree contain a component instance
/// (a named element that names a declared component)? Decides
/// whether the enclosing component carries the slot table.
fn view_has_instance(node: &IrViewNode, component_names: &[String]) -> bool {
    match node {
        IrViewNode::Element { kind, children, .. } => {
            if let IrElementKind::Named(name) = kind
                && component_names.iter().any(|d| d == name)
            {
                return true;
            }
            children
                .iter()
                .any(|c| view_has_instance(c, component_names))
        }
        IrViewNode::For { children, .. } => children
            .iter()
            .any(|c| view_has_instance(c, component_names)),
        IrViewNode::Text { .. } => false,
    }
}

fn emit_expr_init(e: &IrExpr) -> String {
    match e {
        IrExpr::IntLit { value, .. } => value.to_string(),
        IrExpr::FloatLit { value, .. } => format!("{}", value),
        IrExpr::StringLit { value, .. } => js_string(value),
        IrExpr::BoolLit { value, .. } => value.to_string(),
        IrExpr::Ident { .. } => "undefined".into(),
        IrExpr::Call { .. } => "undefined".into(),
        IrExpr::Unary {
            op: IrUnOp::Neg,
            operand,
            ..
        } => match operand.as_ref() {
            IrExpr::IntLit { value, .. } => (-value).to_string(),
            IrExpr::FloatLit { value, .. } => format!("{}", -value),
            _ => "(0 - (".to_string() + &emit_expr_init(operand) + "))",
        },
        IrExpr::Binary { op, lhs, rhs, .. } => {
            "(".to_string()
                + &emit_expr_init(lhs)
                + " "
                + op.js_op()
                + " "
                + &emit_expr_init(rhs)
                + ")"
        }
        // State-field initial values can be `Ok(value)` or
        // `Err(reason)` constructors — Tier 6 lifted the
        // restriction that initial values must be literals. The
        // runtime representation is a tagged object:
        //   {__cui_tag:"Ok", value:v} or {__cui_tag:"Err", reason:r}.
        IrExpr::Ok { value, .. } => {
            "({__cui_tag:\"Ok\",value:".to_string() + &emit_expr_init(value) + "})"
        }
        IrExpr::Err { reason, .. } => {
            "({__cui_tag:\"Err\",reason:".to_string() + &emit_expr_init(reason) + "})"
        }
        // `Some(value)` and `None` are legal state-field
        // initial values (Tier 8): tagged objects like the
        // Result constructors.
        IrExpr::Some { value, .. } => {
            "({__cui_tag:\"Some\",value:".to_string() + &emit_expr_init(value) + "})"
        }
        IrExpr::None { .. } => "({__cui_tag:\"None\"})".to_string(),
        // A `List[T]` literal is a plain JS array; the items are
        // literals or constructor expressions.
        IrExpr::ListLit { items, .. } => {
            let rendered: Vec<String> = items.iter().map(emit_expr_init).collect();
            format!("[{}]", rendered.join(", "))
        }
        // `filter`/`map`/`len` in a state initializer: emitted like
        // the runtime form (Tier 11). A filter/map over another
        // state field in an initializer reads that field before it
        // is initialised — the same forward-reference risk any
        // initializer carries — so prefer literals here.
        IrExpr::Filter {
            list, item, cond, ..
        } => {
            format!(
                "({}).filter(function ({}) {{ return {}; }})",
                emit_expr_init(list),
                item,
                emit_expr_init(cond)
            )
        }
        IrExpr::Map {
            list, item, body, ..
        } => {
            format!(
                "({}).map(function ({}) {{ return {}; }})",
                emit_expr_init(list),
                item,
                emit_expr_init(body)
            )
        }
        IrExpr::Len { list, .. } => format!("({}).length", emit_expr_init(list)),
        // `match` is not a legal state-field initial value in Tier 6
        // (a state field's initial is an expression but a match
        // expression is a runtime construct, not a value). Phase 2
        // can lift this if a use case arrives.
        IrExpr::Match { .. } => "undefined".into(),
        // `await(...)` is a runtime construct, not a value — same
        // reasoning as `match`. Phase 2 may lift this if a use case
        // arrives (e.g. a lazy-initialised state).
        IrExpr::Await { .. } | IrExpr::Cancelled { .. } => "undefined".into(),
    }
}

fn emit_expr_runtime(e: &IrExpr, params: &[&str]) -> String {
    match e {
        IrExpr::IntLit { value, .. } => value.to_string(),
        IrExpr::FloatLit { value, .. } => format!("{}", value),
        IrExpr::StringLit { value, .. } => js_string(value),
        IrExpr::BoolLit { value, .. } => value.to_string(),
        IrExpr::Ident { name, .. } => {
            // An identifier that matches a parameter name is a
            // function parameter, not a state field; emit it
            // bare. Everything else gets the state prefix.
            if params.contains(&name.as_str()) {
                name.clone()
            } else {
                STATE_PREFIX.to_string() + name
            }
        }
        IrExpr::Call { path, args, .. } => emit_call_runtime(path, args, params),
        IrExpr::Unary {
            op: IrUnOp::Neg,
            operand,
            ..
        } => "(0 - (".to_string() + &emit_expr_runtime(operand, params) + "))",
        IrExpr::Binary { op, lhs, rhs, .. } => {
            "(".to_string()
                + &emit_expr_runtime(lhs, params)
                + " "
                + op.js_op()
                + " "
                + &emit_expr_runtime(rhs, params)
                + ")"
        }
        IrExpr::Ok { value, .. } => {
            "({__cui_tag:\"Ok\",value:".to_string() + &emit_expr_runtime(value, params) + "})"
        }
        IrExpr::Err { reason, .. } => {
            "({__cui_tag:\"Err\",reason:".to_string() + &emit_expr_runtime(reason, params) + "})"
        }
        IrExpr::Await { request, .. } => {
            // `await(expr)` becomes a cancellation tracked call:
            //  - the request's effect kind is the cancellation
            //    group (`net.search` -> "net_search");
            //  - starting a call cancels the group's still-pending
            //    one (stale-result protection);
            //  - if a cancelled request resolves, the chain throws
            //    the `__cui_cancelled` sentinel, which the handler
            //    body's try/catch swallows — the rest of the
            //    handler is dropped, so a superseded continuation
            //    cannot write state after a newer call completed.
            //  (The enclosing function is generated as `async
            //  function`; see emit_component.)
            let group = match request.as_ref() {
                IrExpr::Call { path, .. } if !path.is_empty() => path.join("_"),
                _ => "default".to_string(),
            };
            // Tier 17: the third argument is the *component
            // instance's* inflight table — two components awaiting
            // the same effect keep independent cancellation groups,
            // and the instance's `__cui_dispose` cancels its own
            // table on disposal.
            format!(
                "await __cui_call(\"{}\", function () {{ return {}; }}, __cui_inflight)",
                group,
                emit_expr_runtime(request, params)
            )
        }
        IrExpr::Cancelled { .. } => "({__cui_tag:\"Cancelled\"})".to_string(),
        IrExpr::Some { value, .. } => {
            "({__cui_tag:\"Some\",value:".to_string() + &emit_expr_runtime(value, params) + "})"
        }
        IrExpr::None { .. } => "({__cui_tag:\"None\"})".to_string(),
        IrExpr::ListLit { items, .. } => {
            let rendered: Vec<String> =
                items.iter().map(|i| emit_expr_runtime(i, params)).collect();
            format!("[{}]", rendered.join(", "))
        }
        IrExpr::Filter {
            list, item, cond, ..
        } => {
            // `filter(list, x => cond)` — an inline
            // `Array.prototype.filter`. The user's `x` becomes the
            // callback parameter and shadows a state field.
            let mut local_params: Vec<&str> = params.to_vec();
            local_params.push(item.as_str());
            format!(
                "({}).filter(function ({}) {{ return {}; }})",
                emit_expr_runtime(list, params),
                item,
                emit_expr_runtime(cond, &local_params)
            )
        }
        IrExpr::Map {
            list, item, body, ..
        } => {
            let mut local_params: Vec<&str> = params.to_vec();
            local_params.push(item.as_str());
            format!(
                "({}).map(function ({}) {{ return {}; }})",
                emit_expr_runtime(list, params),
                item,
                emit_expr_runtime(body, &local_params)
            )
        }
        IrExpr::Len { list, .. } => {
            // Element count of a list, character count of a
            // string — the same JS `.length`.
            format!("({}).length", emit_expr_runtime(list, params))
        }
        IrExpr::Match {
            scrutinee, arms, ..
        } => {
            // Lower to nested ternaries. For Tier 6 the scrutinee
            // is expected to be a `Result` (Ok/Err) or `Option`
            // (Some/None). Phase 2 may emit a switch table or a
            // decision tree; ternaries are correct and the
            // smallest thing that works.
            emit_match_as_ternary(scrutinee.as_ref(), arms, params)
        }
    }
}

/// Lower a `match` expression to a single ternary chain. The
/// scrutinee is evaluated once into a `__cui_match_<i>` local so
/// each arm's guard and body can refer to it as both a tag
/// (`__cui_match_<i>.__cui_tag`) and a payload
/// (`__cui_match_<i>.value`).
fn emit_match_as_ternary(scrutinee: &IrExpr, arms: &[IrMatchArm], params: &[&str]) -> String {
    use std::cell::Cell;
    thread_local! {
        static COUNTER: Cell<u32> = const { Cell::new(0) };
    }
    let id = COUNTER.with(|c| {
        let n = c.get() + 1;
        c.set(n);
        n
    });
    let scrutinee_var = format!("__cui_match_{}", id);
    let scrutinee_js = emit_expr_runtime(scrutinee, params);
    let mut out = format!(
        "((function () {{ var {0} = {1}; ",
        scrutinee_var, scrutinee_js
    );

    for (i, arm) in arms.iter().enumerate() {
        let guard = pattern_guard(&arm.pattern, &scrutinee_var);
        let body = emit_arm_body(&arm.pattern, &scrutinee_var, &arm.body, params);
        let sep = if i == 0 { "return " } else { "      " };
        out.push_str(sep);
        out.push_str(&guard);
        out.push_str(" ? ");
        out.push_str(&body);
        if i + 1 < arms.len() {
            out.push_str(" : ");
        } else {
            // Last arm — if no arm matches, this should be
            // unreachable (the type checker refused an
            // incomplete match). Emit a value that throws so
            // bugs surface immediately rather than silently
            // returning undefined.
            out.push_str(" : (function () { throw new Error(\"no match arm matched (non-exhaustive match in source)\"); })()");
        }
    }
    out.push_str("; })())");
    out
}

fn pattern_guard(p: &IrPattern, scrutinee_var: &str) -> String {
    match p {
        IrPattern::Wildcard { .. } => "true".to_string(),
        IrPattern::Ident { .. } => "true".to_string(),
        IrPattern::Variant { name, .. } => {
            format!("({0}.__cui_tag === \"{1}\")", scrutinee_var, name)
        }
        IrPattern::UnitVariant { name, .. } => {
            // Zero-payload variant (e.g. `Cancelled`). Matches if
            // the runtime tag equals the variant name. The variant
            // carries no value, so the arm body cannot bind a
            // payload — `Cancelled =>` is a no-arg pattern.
            format!("({0}.__cui_tag === \"{1}\")", scrutinee_var, name)
        }
    }
}

fn emit_arm_body(p: &IrPattern, scrutinee_var: &str, body: &IrExpr, params: &[&str]) -> String {
    match p {
        IrPattern::Wildcard { .. } | IrPattern::Ident { .. } => emit_expr_runtime(body, params),
        IrPattern::Variant { name, binding, .. } => {
            // The payload field depends on the variant: `Ok`
            // stores its under `value`, `Err` under `reason` (see
            // the tagged constructor emitters).
            // A `_` binding skips the IIFE bind entirely.
            let field = if name == "Err" { "reason" } else { "value" };
            if binding == "_" {
                emit_expr_runtime(body, params)
            } else {
                let mut local_params: Vec<&str> = params.to_vec();
                local_params.push(binding.as_str());
                let body_with_param = emit_expr_runtime(body, &local_params);
                format!(
                    "(function () {{ var {0} = {1}.{2}; return {3}; }})()",
                    binding, scrutinee_var, field, body_with_param
                )
            }
        }
        IrPattern::UnitVariant { .. } => {
            // No payload to bind. Just emit the body.
            emit_expr_runtime(body, params)
        }
    }
}

/// Lower a builtin call to its JavaScript form. The capability
/// that authorises the call has already been verified by the
/// checker; this function only picks the symbol to call.
fn emit_call_runtime(path: &[String], args: &[IrExpr], params: &[&str]) -> String {
    if path.len() == 2 && path[0] == "clock" && path[1] == "now" {
        return "__cui_clock_now()".to_string();
    }
    if path.len() == 1 && path[0] == "sleep" {
        // Tier 7: `sleep(ms)` resolves to
        // `{__cui_tag:"Ok",value:undefined}` after `ms` ms.
        let rendered_args: Vec<String> =
            args.iter().map(|a| emit_expr_runtime(a, params)).collect();
        return format!("__cui_sleep_ms({})", rendered_args.join(", "));
    }
    if path.len() == 2 && path[0] == "storage" && (path[1] == "get" || path[1] == "set") {
        // docs/adapters.md: synchronous; `get(key, default)` answers a String, `set(key, value)` a Bool.
        let rendered_args: Vec<String> =
            args.iter().map(|a| emit_expr_runtime(a, params)).collect();
        return format!(
            "__cui_storage_{}({}, __cui_storage_ns)",
            path[1],
            rendered_args.join(", ")
        );
    }
    if path.len() == 2 && path[0] == "location" && path[1] == "current" {
        return "__cui_location_current(__cui_location_digits)".to_string();
    }
    if path.len() == 2 && path[0] == "net" && path[1] == "get" {
        let rendered_args: Vec<String> =
            args.iter().map(|a| emit_expr_runtime(a, params)).collect();
        return format!(
            "__cui_net_get({}, __cui_net_hosts)",
            rendered_args.join(", ")
        );
    }
    if path.len() == 2 && path[0] == "net" && path[1] == "search" {
        // Tier 9: `net.search(q)` resolves to
        // `{__cui_tag:"Ok",value:[...]}` (or Err) after a
        // simulated network delay.
        let rendered_args: Vec<String> =
            args.iter().map(|a| emit_expr_runtime(a, params)).collect();
        return format!("__cui_net_search({})", rendered_args.join(", "));
    }
    let rendered_args: Vec<String> = args.iter().map(|a| emit_expr_runtime(a, params)).collect();
    format!(
        "/* unsupported call {}.{}({}) */",
        path.join("."),
        "",
        rendered_args.join(", ")
    )
}

fn emit_stmt(s: &IrStmt, params: &[&str]) -> String {
    match s {
        IrStmt::Assign { target, value, .. } => {
            STATE_PREFIX.to_string() + target + " = " + &emit_expr_runtime(value, params) + ";"
        }
        IrStmt::Expr { expr, .. } => emit_expr_runtime(expr, params) + ";",
    }
}

// The view walk threads one piece of state per concern (ids, slots, props);
// a context struct is the follow-up, tracked in ROADMAP.md.
#[allow(clippy::too_many_arguments)]
fn emit_view_node(
    next_id: &mut u32,
    indent: &str,
    node: &IrViewNode,
    parent_var: &str,
    params: &[&str],
    components: &[String],
    prop_consumers: &[String],
    has_slots: bool,
    slot_prefix: &str,
    // Tier 17: inside a slotting `For` body, the LHS expression
    // (`__arr2[__i2]`) the instance branch assigns each created
    // slot to, so the For's prune loop can find (and dispose) the
    // slots beyond the list length. `None` elsewhere.
    slot_arr: Option<&str>,
) -> String {
    match node {
        IrViewNode::Text { parts, .. } => {
            let id = *next_id;
            *next_id += 1;
            let var = format!("__n{}", id);
            let mut out = format!(
                "{0}const {1} = document.createElement('span');\n",
                indent, var
            );
            for p in parts {
                match p {
                    IrTextPart::Literal(s) => {
                        out.push_str(&format!(
                            "{0}{1}.appendChild(document.createTextNode({2}));\n",
                            indent,
                            var,
                            js_string(s)
                        ));
                    }
                    IrTextPart::Expr(e) => {
                        out.push_str(&format!(
                            "{0}{1}.appendChild(document.createTextNode(String({2})));\n",
                            indent,
                            var,
                            emit_expr_runtime(e, params)
                        ));
                    }
                }
            }
            out.push_str(&format!(
                "{0}{1}.appendChild({2});\n",
                indent, var, parent_var
            ));
            out
        }
        IrViewNode::For {
            over,
            binding,
            children,
            span: _,
        } => {
            // Tier 8 row repetition: a `for..of` over the list,
            // children emitted with `binding` added to the visible
            // name set so it resolves as the loop variable.
            let mut local_params: Vec<&str> = params.to_vec();
            local_params.push(binding.as_str());
            // Tier 15: a loop that contains (below it) a component
            // instance gets slot machinery — one persistent wrapper
            // per (site, index), pruned to the current length. The
            // loop switches to `forEach` to have the index at hand;
            // loops without instances keep the plain `for..of`.
            if has_slots && children.iter().any(|c| view_has_instance(c, components)) {
                let id = *next_id;
                *next_id += 1;
                let list_var = format!("__list{}", id);
                let key_var = format!("__key{}", id);
                let arr_var = format!("__arr{}", id);
                let child_prefix =
                    format!("({0} + \"s{1}\" + __i{2} + \"_\")", slot_prefix, id, id);
                let mut out = format!(
                    "{0}const {1} = {2};\n",
                    indent,
                    list_var,
                    emit_expr_runtime(over, params)
                );
                out.push_str(&format!(
                    "{0}const {1} = {2} + \"s{3}\";\n",
                    indent, key_var, slot_prefix, id
                ));
                out.push_str(&format!(
                    "{0}const {1} = __cui_slots[{2}] || (__cui_slots[{2}] = []);\n",
                    indent, arr_var, key_var
                ));
                // Tier 17: slots dropped by a shrink are *disposed*
                // — their pending awaits resolve Cancelled and the
                // component's own children dispose transitively —
                // and their keys are forgotten, so growing the list
                // later mounts a fresh component instead of
                // resurrecting a disposed one.
                out.push_str(&format!(
                    "{0}while ({1}.length > {2}.length) {{\n",
                    indent, arr_var, list_var
                ));
                out.push_str(&format!(
                    "{0}    const __dead{1} = {2}.pop();\n",
                    indent, id, arr_var
                ));
                out.push_str(&format!(
                    "{0}    delete __cui_slots[__dead{1}.key];\n",
                    indent, id
                ));
                out.push_str(&format!(
                    "{0}    if (__dead{1}.inst) {{ __dead{1}.inst.__cui_dispose(); }}\n",
                    indent, id
                ));
                out.push_str(&format!("{0}}}\n", indent));
                out.push_str(&format!(
                    "{0}{1}.forEach(function ({2}, __i{3}) {{\n",
                    indent, list_var, binding, id
                ));
                let child_indent = format!("{}    ", indent);
                let child_arr = format!("{0}[__i{1}]", arr_var, id);
                for c in children {
                    out.push_str(&emit_view_node(
                        next_id,
                        &child_indent,
                        c,
                        parent_var,
                        &local_params,
                        components,
                        prop_consumers,
                        has_slots,
                        &child_prefix,
                        Some(&child_arr),
                    ));
                }
                out.push_str(&format!("{0}}});\n", indent));
                return out;
            }
            let mut out = format!(
                "{0}for (const {1} of {2}) {{\n",
                indent,
                binding,
                emit_expr_runtime(over, params)
            );
            let child_indent = format!("{}    ", indent);
            for c in children {
                out.push_str(&emit_view_node(
                    next_id,
                    &child_indent,
                    c,
                    parent_var,
                    &local_params,
                    components,
                    prop_consumers,
                    has_slots,
                    slot_prefix,
                    None,
                ));
            }
            out.push_str(&format!("{0}}}\n", indent));
            out
        }
        IrViewNode::Element {
            kind,
            accessibility,
            bindings,
            children,
            span: _,
        } => {
            let id = *next_id;
            *next_id += 1;
            let var = format!("__n{}", id);
            let tag = kind.tag_name();
            let instance_name: Option<&String> = match kind {
                IrElementKind::Named(name) => {
                    if has_slots && components.iter().any(|d| d == name) {
                        Some(name)
                    } else {
                        None
                    }
                }
                _ => None,
            };
            if let Some(inst_name) = instance_name {
                // Tier 15: the instance site takes the slot path.
                // One persistent wrapper per site; the DOM subtree
                // (and, with it, the child's closures and state)
                // survives parent re-renders. Nothing else about an
                // instance is emitted — an instance takes no
                // bindings of its own besides its properties (the
                // checker refuses the rest, `instance-opaque`), no
                // children, no event wiring (`instance-opaque`).
                let mut props_static: Vec<(String, &IrExpr)> = Vec::new();
                let mut props_dynamic: Vec<(String, &IrExpr)> = Vec::new();
                for b in bindings {
                    if let IrBindingValue::Const { expr, .. } = &b.value {
                        if matches!(expr.as_ref(), IrExpr::Ident { .. }) {
                            props_dynamic.push((b.key.clone(), expr));
                        } else {
                            props_static.push((b.key.clone(), expr));
                        }
                    }
                }
                let child_takes = prop_consumers.iter().any(|d| d == inst_name);
                let key_var = format!("__sk{0}", id);
                let slot_var = format!("__slot{0}", id);
                let mut out = format!(
                    "{0}const {1} = {2} + \"{3}\";\n",
                    indent,
                    key_var,
                    slot_prefix,
                    format_args!("s{}", id)
                );
                out.push_str(&format!(
                    "{0}let {1} = __cui_slots[{2}];\n",
                    indent, slot_var, key_var
                ));
                out.push_str(&format!("{0}if ({1} === undefined) {{\n", indent, slot_var));
                // Tier 17: the slot remembers its own table key so a
                // For prune can delete the entry (no resurrection of
                // a disposed slot when the list grows again); inside
                // a slotting For body the slot is recorded in the
                // For's per-index array (`__arr2[__i2] = __slot`).
                out.push_str(&format!(
                    "{0}    {1} = __cui_slots[{2}] = {{ el: document.createElement('div'), key: {2} }};\n",
                    indent, slot_var, key_var
                ));
                if let Some(arr_lhs) = slot_arr {
                    out.push_str(&format!("{0}    {1} = {2};\n", indent, arr_lhs, slot_var));
                }
                if child_takes {
                    let mut all: Vec<(String, &IrExpr)> = props_static.clone();
                    all.extend(props_dynamic.clone());
                    let rendered: Vec<String> = all
                        .iter()
                        .map(|(k, v)| format!("{0}: {1}", k, emit_expr_runtime(v, params)))
                        .collect();
                    out.push_str(&format!(
                        "{0}    {1}.inst = mount_{2}({1}.el, {{{3}}});\n",
                        indent,
                        slot_var,
                        inst_name,
                        rendered.join(", ")
                    ));
                } else {
                    out.push_str(&format!(
                        "{0}    {1}.inst = mount_{2}({1}.el);\n",
                        indent, slot_var, inst_name
                    ));
                }
                out.push_str(&format!("{0}}}\n", indent));
                if child_takes && !props_dynamic.is_empty() {
                    let rendered: Vec<String> = props_dynamic
                        .iter()
                        .map(|(k, v)| format!("{0}: {1}", k, emit_expr_runtime(v, params)))
                        .collect();
                    out.push_str(&format!(
                        "{0}else {{ {1}.inst.__cui_update({{{2}}}); }}\n",
                        indent,
                        slot_var,
                        rendered.join(", ")
                    ));
                }
                out.push_str(&format!(
                    "{0}{1}.appendChild({2}.el);\n",
                    indent, parent_var, slot_var
                ));
                return out;
            }
            let mut out = format!(
                "{0}const {1} = document.createElement('{2}');\n",
                indent, var, tag
            );
            if let Some(cls) = kind.layout_class() {
                out.push_str(&format!("{0}{1}.classList.add('{2}');\n", indent, var, cls));
            }
            if let Some(role) = &accessibility.role {
                let r = match role {
                    IrRole::Text => "text",
                    IrRole::Heading => "heading",
                    IrRole::Button => "button",
                    IrRole::Other(s) => s.as_str(),
                };
                out.push_str(&format!(
                    "{0}{1}.setAttribute('role', {2});\n",
                    indent,
                    var,
                    js_string(r)
                ));
            }
            if let Some(label) = &accessibility.label {
                out.push_str(&format!(
                    "{0}{1}.setAttribute('aria-label', {2});\n",
                    indent,
                    var,
                    js_string(label)
                ));
            }

            // Apply bindings.
            let mut click_handler: Option<String> = None;
            let mut input_handler: Option<String> = None;
            let mut input_value: Option<String> = None;
            let mut button_label: Option<String> = None;
            // Tier 13: on a component instance, `Const` bindings
            // are *properties* — constant initial values for the
            // child's state fields. They go into the mount call's
            // props object, not into wrapper attributes.
            let mut props_obj: Vec<(String, &IrExpr)> = Vec::new();
            for b in bindings {
                let as_prop = match &b.value {
                    IrBindingValue::Const { expr, .. } => Some(expr),
                    _ => None,
                };
                if matches!(kind, IrElementKind::Named(_))
                    && let Some(expr) = as_prop
                {
                    props_obj.push((b.key.clone(), expr));
                    continue;
                }
                match &b.value {
                    IrBindingValue::Const { .. } => {
                        // A `Const` binding on a primitive (a
                        // non-string label etc.) is not expressible
                        // as an HTML attribute value today.
                        out.push_str(&format!(
                            "{0}// property value on a primitive cannot be set as an attribute (Tier 13)\n",
                            indent
                        ));
                    }
                    IrBindingValue::String(s) => {
                        if b.key == "label" {
                            if matches!(kind, IrElementKind::Button) {
                                button_label = Some(s.clone());
                            } else {
                                out.push_str(&format!(
                                    "{0}{1}.setAttribute('aria-label', {2});\n",
                                    indent,
                                    var,
                                    js_string(s)
                                ));
                            }
                        } else if b.key == "value" {
                            if matches!(kind, IrElementKind::TextField) {
                                input_value = Some(s.clone());
                            } else {
                                out.push_str(&format!(
                                    "{0}// value: on a non-TextField (Phase 2+)\n",
                                    indent
                                ));
                            }
                        } else {
                            out.push_str(&format!(
                                "{0}{1}.setAttribute({2}, {3});\n",
                                indent,
                                var,
                                js_string(&b.key),
                                js_string(s)
                            ));
                        }
                    }
                    IrBindingValue::EventRef(name) => {
                        if b.key == "on" {
                            if matches!(kind, IrElementKind::Button) {
                                click_handler = Some(name.clone());
                            } else if matches!(kind, IrElementKind::TextField) {
                                input_handler = Some(name.clone());
                            } else {
                                out.push_str(&format!(
                                    "{0}// on: {1} on a non-button/non-textfield primitive (Phase 2+)\n",
                                    indent, name
                                ));
                            }
                        } else {
                            out.push_str(&format!(
                                "{0}// {1}: {2} on a primitive (Phase 2+)\n",
                                indent, b.key, name
                            ));
                        }
                    }
                    IrBindingValue::StateRef(name) => {
                        if b.key == "value" {
                            if matches!(kind, IrElementKind::TextField) {
                                // One-way binding to a state field;
                                // re-render reflects the new value.
                                input_value = Some(format!("{}{}", STATE_PREFIX, name));
                            } else {
                                out.push_str(&format!(
                                    "{0}// value: state ref on a non-TextField (Phase 2+)\n",
                                    indent
                                ));
                            }
                        } else {
                            out.push_str(&format!(
                                "{0}// {1}: {2} on a primitive (Phase 2+)\n",
                                indent, b.key, name
                            ));
                        }
                    }
                    IrBindingValue::Role(r) => {
                        let role_str = match r {
                            IrRole::Text => "text",
                            IrRole::Heading => "heading",
                            IrRole::Button => "button",
                            IrRole::Other(s) => s.as_str(),
                        };
                        out.push_str(&format!(
                            "{0}{1}.setAttribute('role', {2});\n",
                            indent,
                            var,
                            js_string(role_str)
                        ));
                    }
                }
            }

            // Children.
            let child_indent = format!("{}    ", indent);
            if matches!(kind, IrElementKind::Text) {
                for c in children {
                    if let IrViewNode::Text { parts, .. } = c {
                        for p in parts {
                            match p {
                                IrTextPart::Literal(s) => {
                                    out.push_str(&format!(
                                        "{0}{1}.appendChild(document.createTextNode({2}));\n",
                                        indent,
                                        var,
                                        js_string(s)
                                    ));
                                }
                                IrTextPart::Expr(e) => {
                                    out.push_str(&format!(
                                        "{0}{1}.appendChild(document.createTextNode(String({2})));\n",
                                        indent, var, emit_expr_runtime(e, params)
                                    ));
                                }
                            }
                        }
                    }
                }
            } else {
                // A Button's visible text is its `label` when it has no children of its own: the `label` reaches
                // here as the accessibility label (not as a binding), and a button with an `aria-label` and an
                // empty text node showed nothing.
                let visible_label = button_label.clone().or_else(|| {
                    if matches!(kind, IrElementKind::Button) && children.is_empty() {
                        accessibility.label.clone()
                    } else {
                        None
                    }
                });
                if let Some(ref label) = visible_label {
                    out.push_str(&format!(
                        "{0}{1}.appendChild(document.createTextNode({2}));\n",
                        indent,
                        var,
                        js_string(label)
                    ));
                } else if matches!(kind, IrElementKind::Button) {
                    out.push_str(&format!(
                        "{0}{1}.appendChild(document.createTextNode(\"\"));\n",
                        indent, var
                    ));
                }
                for c in children {
                    out.push_str(&emit_view_node(
                        next_id,
                        &child_indent,
                        c,
                        &var,
                        params,
                        components,
                        prop_consumers,
                        has_slots,
                        slot_prefix,
                        slot_arr,
                    ));
                }
            }

            // TextField: set the value attribute, type, and initial value.
            if matches!(kind, IrElementKind::TextField) {
                out.push_str(&format!(
                    "{0}{1}.setAttribute('type', 'text');\n",
                    indent, var
                ));
                if let Some(ref v) = input_value {
                    out.push_str(&format!("{0}{1}.value = {2};\n", indent, var, v));
                }
            }

            // Append to parent.
            out.push_str(&format!(
                "{0}{2}.appendChild({1});\n",
                indent, var, parent_var
            ));

            // Wire up event handlers.
            if let Some(event_name) = click_handler {
                out.push_str(&format!(
                    "{0}{1}.addEventListener('click', __on_{2});\n",
                    indent, var, event_name
                ));
            }
            if let Some(event_name) = input_handler {
                out.push_str(&format!(
                    "{0}{1}.addEventListener('input', function (e) {{ __on_{2}(e.target.value); }});\n",
                    indent, var, event_name
                ));
            }

            out
        }
    }
}

fn js_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

