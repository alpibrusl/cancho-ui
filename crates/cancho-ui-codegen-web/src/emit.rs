//! The web backend's emitter for Tier 2: state, events, reactive
//! re-render, the `Button` primitive, and string interpolation.
//!
//! ## Reactive model
//!
//! Each component has a single `mount_<Name>(root)` function. State
//! is held in plain `let` variables inside an IIFE so that closures
//! (event handlers) capture them by reference. An event handler
//! updates state and calls `__render()` which:
//!
//! 1. Builds a new view tree by re-evaluating the view block
//!    against the current state.
//! 2. Creates a fresh DOM subtree.
//! 3. Replaces the existing root's children with the new subtree.
//!
//! This is coarse-grained reactivity — every state change
//! re-renders the entire component. The language semantics are the
//! same as fine-grained reactivity; only the implementation
//! differs. Phase 3 may swap this for fine-grained without changing
//! the IR.

use cancho_ui_ir::ir::*;

use crate::adapters::*;
use crate::expr::{emit_expr_init, emit_expr_runtime};
use crate::view::{emit_view_node, view_has_instance};

pub fn module_for_file(ir: &IrFile) -> String {
    emit_module(ir, None)
}

/// What `emit_module_with` may be told (docs/mobile-backend.md section 9).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EmitOptions {
    /// Mount the last component into `#root` when the module is imported (the default). `false` keeps the export and
    /// omits the side effect.
    pub auto_mount: bool,
}

impl Default for EmitOptions {
    fn default() -> Self {
        EmitOptions { auto_mount: true }
    }
}

pub fn emit_module(ir: &IrFile, source_name: Option<&str>) -> String {
    emit_module_with(ir, source_name, &EmitOptions::default())
}

/// The `// Source:` comment shows a path; only printable ASCII goes into the module (section 9.2).
fn ascii_comment(s: &str) -> String {
    s.chars()
        .map(|c| if (' '..='~').contains(&c) { c } else { '?' })
        .collect()
}

pub fn emit_module_with(ir: &IrFile, source_name: Option<&str>, options: &EmitOptions) -> String {
    let mut out = String::new();
    out.push_str("// Generated by cancho-ui build (Tier 4, web backend).\n");
    if let Some(name) = source_name {
        out.push_str("// Source: ");
        out.push_str(&ascii_comment(name));
        out.push('\n');
    }
    out.push_str("// Schema: ");
    out.push_str(&ir.schema);
    out.push(' ');
    out.push_str(&ir.version);
    out.push('\n');
    out.push_str("//\n");
    out.push_str("// Do not edit by hand. Re-run `cancho-ui build` to regenerate.\n");
    out.push('\n');

    // Platform adapters: thin wrappers over browser APIs. Phase 2
    // will move these into separately-imported cancho-ui source
    // files (the "platform adapter" example in the proposal). For
    // Tier 4 we emit them inline so the binary is self-contained.
    let mut any_clock = false;
    let mut any_sleep = false;
    let mut any_network = false;
    let mut any_net_get = false;
    let mut any_net_post = false;
    let mut any_net_put = false;
    let mut any_net_delete = false;
    let mut any_location = false;
    let mut any_router = false;
    let mut any_stream = false;
    let mut locale_langs: Vec<String> = Vec::new();
    let mut any_storage = false;
    let mut any_cancel = false;
    for c in &ir.components {
        for e in &c.reachable_effects {
            if e.capability == "Clock" {
                any_clock = true;
            }
            if e.capability == "Locale" {
                for l in crate::i18n::languages(c) {
                    if !locale_langs.contains(&l) {
                        locale_langs.push(l);
                    }
                }
            }
            if e.capability == "Network" && e.path == ["subscribe"] {
                any_stream = true;
            } else if e.capability == "Network"
                && e.path.last().is_some_and(|f| f == "get" || f == "fetch")
            {
                any_net_get = true;
            } else if e.capability == "Network" {
                any_network = true;
            }
            if e.capability == "NetworkWrite" {
                match e.path.last().map(String::as_str) {
                    Some("put") => any_net_put = true,
                    Some("delete") => any_net_delete = true,
                    _ => any_net_post = true,
                }
            }
            if e.capability == "Storage" {
                any_storage = true;
            }
            if e.capability == "Location" {
                any_location = true;
            }
            if e.capability == "Router" {
                any_router = true;
            }
        }
        for arm in c.events.iter().flat_map(|e| e.body.iter()) {
            if body_uses_await(arm) || body_uses_sleep(arm) {
                any_sleep = true;
            }
        }
        if view_node_uses_await_or_sleep(&c.view.body) {
            any_sleep = true;
        }
        // Tier 10: any `await(...)` anywhere needs the
        // cancellation runtime (`__cui_call`, sentinel).
        if c.events.iter().any(|e| e.body.iter().any(body_uses_await))
            || view_node_uses_await_or_sleep(&c.view.body)
        {
            any_cancel = true;
        }
    }
    if any_clock {
        out.push_str(CLOCK_ADAPTER_JS);
        out.push('\n');
    }
    if any_storage {
        out.push_str(STORAGE_ADAPTER_JS);
        out.push('\n');
    }
    if any_sleep {
        out.push_str(SLEEP_ADAPTER_JS);
        out.push('\n');
    }
    if any_network {
        out.push_str(NETWORK_ADAPTER_JS);
        out.push('\n');
    }
    // docs/adapters.md section 18: a module in which some component declares a `Credential` carries the helpers
    // that attach it, and the variable through which a mount hands each component the tokens it was given.
    let any_credential = ir
        .components
        .iter()
        .any(|c| c.requires.iter().any(|r| r.name == "Credential"));
    if any_net_get || any_net_post || any_net_put || any_net_delete || any_credential || any_stream
    {
        out.push_str(CREDENTIAL_ADAPTER_JS);
        out.push('\n');
    }
    if any_credential {
        out.push_str("let __cui_cur_creds = null;\n");
        out.push('\n');
    }
    if !locale_langs.is_empty() {
        out.push_str(&crate::i18n::adapter_js(&locale_langs));
        out.push('\n');
    }
    if any_stream {
        out.push_str(&crate::stream::adapter_js());
        out.push('\n');
    }
    if any_net_get {
        out.push_str(NET_GET_ADAPTER_JS);
        out.push('\n');
    }
    if any_net_post {
        out.push_str(NET_POST_ADAPTER_JS);
        out.push('\n');
    }
    if any_net_put {
        out.push_str(NET_PUT_ADAPTER_JS);
        out.push('\n');
    }
    if any_net_delete {
        out.push_str(NET_DELETE_ADAPTER_JS);
        out.push('\n');
    }
    if any_location {
        out.push_str(LOCATION_ADAPTER_JS);
        out.push('\n');
    }
    if any_router {
        out.push_str(ROUTER_ADAPTER_JS);
        out.push('\n');
    }
    if ir.components.iter().any(|c| view_has_chart(&c.view.body)) {
        out.push_str(CHART_ADAPTER_JS);
        out.push('\n');
    }
    if ir.components.iter().any(|c| view_has_file(&c.view.body)) {
        out.push_str(FILE_ADAPTER_JS);
        out.push('\n');
    }
    if any_cancel {
        out.push_str(CANCEL_ADAPTER_JS);
        out.push('\n');
    } else {
        // Every handler's catch compares with the sentinel; with no await nothing throws it, but the name must exist,
        // or any other error a handler throws (a non-finite result, `__cui_fin`) would surface as a ReferenceError.
        out.push_str("const __cui_cancelled = Symbol(\"__cui_cancelled\");\n\n");
    }
    // A control the user is using must keep focus across the rebuild a state change causes.
    let keep_focus = ir.components.iter().any(|c| {
        view_has_focusable(&c.view.body)
            || c.schedules.iter().any(|s| s.kind == IrScheduleKind::Route)
    });
    if keep_focus {
        out.push_str(FOCUS_ADAPTER_JS);
        out.push('\n');
    }

    // Tier 13: components some instance passes a property to get
    // the `props`-aware mount signature.
    let mut prop_consumers: Vec<String> = Vec::new();
    for c in &ir.components {
        collect_prop_consumers(&c.view.body, &mut prop_consumers);
    }

    let component_names: Vec<String> = ir.components.iter().map(|c| c.name.clone()).collect();
    let adapters_end = out.len();
    for c in &ir.components {
        out.push_str(&emit_component(
            c,
            &component_names,
            &prop_consumers,
            keep_focus,
            any_credential,
        ));
        out.push('\n');
    }

    // `json.get` is pure, so no capability tells the emitter it is used: look at what was emitted.
    if out[adapters_end..].contains("__cui_json_get(")
        || out[adapters_end..].contains("__cui_json_items(")
    {
        out.insert_str(adapters_end, JSON_GET_JS);
    }

    // The list builtins (docs/lists.md) are pure too: emit the helpers that the emitted program calls.
    out.insert_str(
        adapters_end,
        &crate::lists::helpers_used(&out[adapters_end..]),
    );

    {
        let set = if any_credential {
            "__cui_cur_creds = __cui_creds; "
        } else {
            ""
        };
        let tail = out.split_off(adapters_end);
        out.push_str(&tail.replace("/*CUI_SETCREDS*/", set));
    }

    if let Some(last) = ir.components.last() {
        if options.auto_mount {
            out.push_str("const root = (typeof document !== 'undefined') ? document.getElementById('root') : null;\n");
            out.push_str("if (root) { mount_");
            out.push_str(&last.name);
            out.push_str("(root); }\n");
        }
        if any_credential {
            // docs/adapters.md section 18: the entry takes the tokens, `mount_X(root, { credentials: { api: token } })`.
            out.push_str("function __cui_mount_entry(root, options) {\n");
            out.push_str("    var given = {};\n");
            out.push_str("    var from = options && typeof options === 'object' && options.credentials && typeof options.credentials === 'object' ? options.credentials : {};\n");
            out.push_str("    for (var k in from) { if (Object.prototype.hasOwnProperty.call(from, k) && typeof from[k] === 'string') { given[k] = from[k]; } }\n");
            out.push_str("    __cui_cur_creds = given;\n");
            out.push_str("    try { return mount_");
            out.push_str(&last.name);
            out.push_str("(root); } finally { __cui_cur_creds = null; }\n}\n");
            out.push_str("export { __cui_mount_entry as mount_");
            out.push_str(&last.name);
            out.push_str(" };\n");
        } else {
            out.push_str("export { mount_");
            out.push_str(&last.name);
            out.push_str(" };\n");
        }
    }

    out
}

/// Does a view hold a control the user can focus (a `Button` or a `TextField`), directly or in a `For`?
fn view_has_chart(node: &IrViewNode) -> bool {
    match node {
        IrViewNode::Element { kind, children, .. } => {
            matches!(kind, IrElementKind::Chart) || children.iter().any(view_has_chart)
        }
        IrViewNode::For { children, .. } | IrViewNode::If { children, .. } => {
            children.iter().any(view_has_chart)
        }
        IrViewNode::Text { .. } => false,
    }
}

fn view_has_file(node: &IrViewNode) -> bool {
    match node {
        IrViewNode::Element { kind, children, .. } => {
            matches!(kind, IrElementKind::FileField) || children.iter().any(view_has_file)
        }
        IrViewNode::For { children, .. } | IrViewNode::If { children, .. } => {
            children.iter().any(view_has_file)
        }
        IrViewNode::Text { .. } => false,
    }
}

fn view_has_focusable(node: &IrViewNode) -> bool {
    match node {
        IrViewNode::Element { kind, children, .. } => {
            kind.is_focusable() || children.iter().any(view_has_focusable)
        }
        IrViewNode::For { children, .. } | IrViewNode::If { children, .. } => {
            children.iter().any(view_has_focusable)
        }
        IrViewNode::Text { .. } => false,
    }
}

/// Recursive helper: does this statement contain an `await`
/// expression? Used to decide whether to emit the async helper.
fn body_uses_await(s: &IrStmt) -> bool {
    match s {
        IrStmt::Assign { value, .. } => expr_uses_await(value),
        IrStmt::Expr { expr, .. } => expr_uses_await(expr),
        // The condition is pure; a branch may await.
        IrStmt::If { then, else_, .. } => then.iter().chain(else_).any(body_uses_await),
    }
}

fn expr_uses_await(e: &IrExpr) -> bool {
    match e {
        IrExpr::Await { .. } => true,
        IrExpr::Binary { lhs, rhs, .. } => expr_uses_await(lhs) || expr_uses_await(rhs),
        IrExpr::Unary { operand, .. } => expr_uses_await(operand),
        IrExpr::If {
            cond, then, else_, ..
        } => expr_uses_await(cond) || expr_uses_await(then) || expr_uses_await(else_),
        IrExpr::Call { args, .. } => args.iter().any(expr_uses_await),
        IrExpr::Ok { value, .. } => expr_uses_await(value),
        IrExpr::Err { reason, .. } => expr_uses_await(reason),
        IrExpr::Match {
            scrutinee, arms, ..
        } => expr_uses_await(scrutinee) || arms.iter().any(|a| expr_uses_await(&a.body)),
        _ => false,
    }
}

/// Recursive helper: does this statement contain a call to
/// `sleep(...)`? Used to decide whether to emit the sleep adapter.
fn body_uses_sleep(s: &IrStmt) -> bool {
    match s {
        IrStmt::Assign { value, .. } => expr_uses_sleep(value),
        IrStmt::Expr { expr, .. } => expr_uses_sleep(expr),
        IrStmt::If { then, else_, .. } => then.iter().chain(else_).any(body_uses_sleep),
    }
}

fn expr_uses_sleep(e: &IrExpr) -> bool {
    match e {
        IrExpr::Call { path, args, .. } => {
            (path.len() == 1 && path[0] == "sleep") || args.iter().any(expr_uses_sleep)
        }
        IrExpr::Binary { lhs, rhs, .. } => expr_uses_sleep(lhs) || expr_uses_sleep(rhs),
        IrExpr::Unary { operand, .. } => expr_uses_sleep(operand),
        IrExpr::If {
            cond, then, else_, ..
        } => expr_uses_sleep(cond) || expr_uses_sleep(then) || expr_uses_sleep(else_),
        IrExpr::Ok { value, .. } => expr_uses_sleep(value),
        IrExpr::Err { reason, .. } => expr_uses_sleep(reason),
        IrExpr::Match {
            scrutinee, arms, ..
        } => expr_uses_sleep(scrutinee) || arms.iter().any(|a| expr_uses_sleep(&a.body)),
        _ => false,
    }
}

fn view_node_uses_await_or_sleep(node: &IrViewNode) -> bool {
    match node {
        IrViewNode::Element { children, .. } => children.iter().any(view_node_uses_await_or_sleep),
        IrViewNode::Text { parts, .. } => parts.iter().any(|p| match p {
            IrTextPart::Literal(_) => false,
            IrTextPart::Expr(e) => expr_uses_await(e) || expr_uses_sleep(e),
        }),
        IrViewNode::For { over, children, .. } => {
            expr_uses_await(over)
                || expr_uses_sleep(over)
                || children.iter().any(view_node_uses_await_or_sleep)
        }
        IrViewNode::If { cond, children, .. } => {
            expr_uses_await(cond)
                || expr_uses_sleep(cond)
                || children.iter().any(view_node_uses_await_or_sleep)
        }
    }
}

pub(crate) const STATE_PREFIX: &str = "__state_";

/// Tier 13: which components receive properties from some
/// instance? Those get the `props`-aware mount signature.
fn collect_prop_consumers(node: &IrViewNode, out: &mut Vec<String>) {
    match node {
        IrViewNode::Element {
            kind,
            bindings,
            children,
            ..
        } => {
            if let IrElementKind::Named(name) = kind
                && bindings
                    .iter()
                    .any(|b| matches!(b.value, IrBindingValue::Const { .. }))
            {
                out.push(name.clone());
            }
            for c in children {
                collect_prop_consumers(c, out);
            }
        }
        IrViewNode::For { children, .. } | IrViewNode::If { children, .. } => {
            for c in children {
                collect_prop_consumers(c, out);
            }
        }
        IrViewNode::Text { .. } => {}
    }
}

fn emit_component(
    c: &IrComponent,
    component_names: &[String],
    prop_consumers: &[String],
    keep_focus: bool,
    module_credentials: bool,
) -> String {
    // Tier 13: components that some instance passes properties to
    // take a `props` argument; their state initializers consult
    // it, falling back to the declared default. Components never
    // instantiated with properties keep the plain signature and
    // initializers.
    let takes_props = prop_consumers.contains(&c.name);
    // Tier 15: components whose view instantiates subcomponents
    // carry a slot table — one persistent wrapper per instance
    // site, surviving re-renders so that a child's state survives
    // the parent re-render instead of resetting.
    // Tier 15: does this view subtree contain a component instance?
    let has_instances = view_has_instance(&c.view.body, component_names);
    // Tier 17: does any of this component's code await? Awaiting
    // components get a *per-instance* inflight table (two
    // components with the same effect keep independent groups) and
    // a dispose handle that cancels their pending requests.
    let has_awaits = c.events.iter().any(|e| e.body.iter().any(body_uses_await))
        || view_node_uses_await_or_sleep(&c.view.body);
    let has_schedules = !c.schedules.is_empty();
    // docs/screen-focus.md section 3: only a component with `route` keeps the page title.
    let routed = c.schedules.iter().any(|s| s.kind == IrScheduleKind::Route);
    let needs_dispose = has_awaits || has_instances || has_schedules;
    let mut out = String::new();
    out.push_str("// Component: ");
    out.push_str(&c.name);
    out.push_str(" (id ");
    out.push_str(&c.id.0.to_string());
    out.push_str(")\n");
    out.push_str("function mount_");
    out.push_str(&c.name);
    if takes_props {
        out.push_str("(root, props) {\n");
    } else {
        out.push_str("(root) {\n");
    }
    out.push_str("    ");
    // Tier 15: a prop-consuming child returns its update handle
    // (the IIFE's result), so the parent's slot can call
    // `__cui_update` on later re-renders. Children that never
    // receive properties return nothing.
    // Tier 17: a component that awaits or hosts instances returns
    // a `__cui_dispose` handle as well — its slot's removal calls
    // it, and its own disposal cascades to its children.
    let returns_handle = takes_props || needs_dispose;
    if returns_handle {
        out.push_str("return ");
    }
    out.push_str("(function () {\n");

    // docs/i18n.md: the language in use is the component's, chosen at mount from the browser's languages; the page's `lang` and `dir` follow it.
    if c.reachable_effects.iter().any(|e| e.capability == "Locale") {
        out.push_str(&format!(
            "        const __cui_msgs = {};\n        const __cui_loc = {{ lang: __cui_locale_init(__cui_msgs.langs), langs: __cui_msgs.langs }};\n        __cui_doc(__cui_loc.lang);\n",
            crate::i18n::component_json(c)
        ));
    }
    for s in &c.state {
        out.push_str("        let ");
        out.push_str(STATE_PREFIX);
        out.push_str(&s.name);
        out.push_str(" = ");
        if takes_props {
            out.push_str(&format!(
                "(props == null || props.{0} === undefined) ? ({1}) : props.{0}",
                s.name,
                emit_expr_init(&s.initial)
            ));
        } else {
            out.push_str(&emit_expr_init(&s.initial));
        }
        out.push_str(";\n");
    }

    // Tier 15: the slot table lives at mount-function scope so
    // `__render()` can re-attach the same wrapper elements (and
    // with them the mounted children's state). Only components
    // with instance sites in their view pay for it.
    if has_instances {
        out.push_str("        const __cui_slots = { };\n");
    }

    // Tier 17: the per-instance cancellation table. Only an
    // awaiting component carries one; with it, two components
    // awaiting the same effect never cancel each other's requests.
    if has_awaits {
        out.push_str("        const __cui_inflight = { };\n");
    }
    // docs/schedules.md section 7: the timers of `every`, cleared on disposal, and for each event an `every` runs,
    // the number of its runs in flight (a click's included): a tick that finds one running is skipped.
    let ticked: Vec<&str> = c
        .schedules
        .iter()
        .filter(|s| matches!(s.kind, IrScheduleKind::Every(_)))
        .map(|s| s.event.as_str())
        .collect();
    if has_schedules && !ticked.is_empty() {
        // docs/schedules.md section 11: the page is active unless it is hidden; a tick does not run while it is not.
        out.push_str("        const __cui_every = [];\n");
        out.push_str(
            "        let __cui_active = typeof document === 'undefined' || document.visibilityState !== 'hidden';\n",
        );
        let mut names: Vec<&str> = ticked.clone();
        names.sort_unstable();
        names.dedup();
        let fields: Vec<String> = names.iter().map(|n| format!("{n}: 0")).collect();
        out.push_str(&format!(
            "        const __cui_busy = {{ {} }};\n",
            fields.join(", ")
        ));
    }
    // docs/adapters.md 10: the hosts other than this page's own that `net.get` may reach, from the bounds of
    // `requires Network(..)`, lower-cased. Per instance, so two components keep their own allow-lists.
    if c.requires.iter().any(|r| r.name == "Storage") {
        // docs/adapters.md 12: `requires Storage("ns")` keeps this component's keys under `cui:ns:`;
        // without a bound the keys are under `cui:` as before.
        let ns = c
            .requires
            .iter()
            .filter(|r| r.name == "Storage")
            .find_map(|r| r.bounds.first())
            .map(String::as_str)
            .unwrap_or("");
        out.push_str(&format!("        const __cui_storage_ns = \"{ns}\";\n"));
    }
    if c.requires.iter().any(|r| r.name == "Location") {
        let fine = c
            .requires
            .iter()
            .filter(|r| r.name == "Location")
            .any(|r| r.bounds.iter().any(|b| b == "fine"));
        out.push_str(&format!(
            "        const __cui_location_digits = {};\n",
            if fine { 5 } else { 2 }
        ));
    }
    if module_credentials {
        // docs/adapters.md section 18: the tokens this instance was mounted with (a child gets its parent's).
        out.push_str("        const __cui_creds = __cui_cur_creds;\n");
    }
    if c.requires
        .iter()
        .any(|r| r.name == "Network" || r.name == "NetworkWrite")
    {
        let cred = c.requires.iter().find(|r| r.name == "Credential");
        match cred {
            Some(r) => {
                let name = r.bounds.first().map(String::as_str).unwrap_or("");
                let hosts: Vec<String> = r.bounds[1..]
                    .iter()
                    .map(|h| format!("\"{}\"", h.to_ascii_lowercase()))
                    .collect();
                // A component that can set its own token (docs/bearer-token.md) sends its first requests, the sign-in among them,
                // without one; a component that cannot is blocked until the page supplies it (docs/adapters.md section 18).
                let anon = c
                    .reachable_effects
                    .iter()
                    .any(|e| e.path == ["credential", "set"]);
                out.push_str(&format!(
                    "        const __cui_cred = {{ name: \"{name}\", hosts: [{}], anon: {anon}, token: (__cui_creds && Object.prototype.hasOwnProperty.call(__cui_creds, \"{name}\")) ? __cui_creds[\"{name}\"] : null }};\n",
                    hosts.join(", ")
                ));
            }
            None => out.push_str("        const __cui_cred = null;\n"),
        }
    }
    if c.requires.iter().any(|r| r.name == "Network") {
        let hosts: Vec<String> = c
            .requires
            .iter()
            .filter(|r| r.name == "Network")
            .flat_map(|r| r.bounds.iter())
            .map(|b| format!("\"{}\"", b.to_ascii_lowercase()))
            .collect();
        out.push_str(&format!(
            "        const __cui_net_hosts = [{}];\n",
            hosts.join(", ")
        ));
    }

    for e in &c.events {
        // Event handlers are emitted as `async function` so that
        // `await(...)` can suspend until a `Request[T]` resolves
        // and the rest of the body runs with the resolved value.
        // Handlers that never use `await` pay one microtask
        // (the same cost as a resolved Promise). Tier 7 keeps
        // this uniform; Phase 2 can special-case sync-only
        // handlers.
        out.push_str("        async function __on_");
        out.push_str(&e.name);
        out.push('(');
        out.push_str(&e.params.join(", "));
        out.push_str(") {\n");
        let param_set: Vec<&str> = e.params.iter().map(|s| s.as_str()).collect();
        // If the body awaits, paint the pre-await state first: a
        // loading status set before `await(...)` must reach the
        // DOM while the handler is suspended, so emit a
        // synchronous `__render()` after the statements that
        // precede the first await. (The final `__render()` at the
        // end of the handler repaints the post-resolution state.)
        //
        // The whole body sits in a try/catch that swallows the
        // `__cui_cancelled` sentinel: when a request is
        // superseded, its resolution throws the sentinel out of
        // the awaiting statement and the *rest of the handler*
        // never runs — the stale continuation is dropped, so a
        // slower old request cannot clobber the newer one's
        // state. Other exceptions rethrow.
        let counted = ticked.contains(&e.name.as_str());
        if counted {
            out.push_str(&format!("            __cui_busy.{}++;\n", e.name));
        }
        // Segment atomicity (docs/semantics.md, "A handler that faults"): a handler that writes and then has a statement
        // that can fault keeps a snapshot of the fields it writes, taken at its start and again after each statement
        // that awaited (a commit point), and puts it back if a statement throws. `__snap` is null while an awaiting
        // statement runs: the statements before it were committed when the handler suspended, and the statement writes
        // only when it completes, so a fault inside it has nothing to undo (and the old snapshot, from before the
        // suspension, must not be put back over what other events wrote meanwhile).
        let written: Vec<&str> = {
            let mut w: Vec<&str> = Vec::new();
            for s in IrStmt::leaves(&e.body) {
                if let IrStmt::Assign { target, .. } = s
                    && !w.contains(&target.as_str())
                {
                    w.push(target);
                }
            }
            w
        };
        let atomic = IrStmt::leaves(&e.body).len() >= 2 && !written.is_empty();
        let snap_list = written
            .iter()
            .map(|t| format!("{STATE_PREFIX}{t}"))
            .collect::<Vec<_>>()
            .join(", ");
        if atomic {
            out.push_str(&format!("            let __snap = [{snap_list}];\n"));
        }
        out.push_str("            try {\n");
        let snap = atomic.then_some(snap_list.as_str());
        for (i, s) in e.body.iter().enumerate() {
            // Paint what the handler has written before each suspension, not only the first (docs/semantics.md, "A
            // handler that faults"); an awaiting statement that starts the handler has written nothing yet.
            emit_stmt(&mut out, s, &param_set, snap, "                ", i > 0);
        }
        out.push_str("                __render();\n");
        out.push_str("            } catch (e) {\n");
        if atomic {
            out.push_str("                if (e !== __cui_cancelled) {\n");
            out.push_str(&format!(
                "                    if (__snap) {{ [{snap_list}] = __snap; }}\n"
            ));
            out.push_str("                    __render();\n");
            out.push_str("                    throw e;\n");
            out.push_str("                }\n");
        } else {
            out.push_str("                if (e !== __cui_cancelled) { throw e; }\n");
        }
        if counted {
            out.push_str("            } finally {\n");
            out.push_str(&format!("                __cui_busy.{}--;\n", e.name));
        }
        out.push_str("            }\n");
        out.push_str("        }\n");
    }

    out.push_str(&crate::controls::submit_blocked_table(c, "        "));
    // docs/screen-focus.md section 3: the `If` sites that are drawn now and in the render before, and where the heading of the
    // screen that last appeared is.
    out.push_str("        let __cui_ifs_prev = {};\n        let __cui_screen_of = null;\n");
    out.push_str("        function __render() {\n            const __cui_ifs_now = {};\n");
    if keep_focus {
        out.push_str("            const __focus = __cui_focus_save(root);\n");
    }
    out.push_str("            root.textContent = '';\n");
    let mut node_id = 0u32;
    let view_body = emit_view_node(
        &mut node_id,
        "            ",
        &c.view.body,
        "root",
        &[],
        component_names,
        prop_consumers,
        has_instances,
        "\"\"",
        None,
    );
    out.push_str(&view_body);
    if view_body.contains("__cui_ifs_now[") {
        out.push_str("            const __cui_drawn = [];\n            for (const k in __cui_ifs_now) { if (!__cui_ifs_prev[k]) { __cui_drawn.push(__cui_ifs_now[k]); } }\n            __cui_ifs_prev = {};\n            for (const k in __cui_ifs_now) { __cui_ifs_prev[k] = true; }\n            if (__cui_drawn.length) { __cui_screen_of = { path: __cui_appeared(root, __cui_drawn) }; }\n");
    }
    if keep_focus {
        // A control that had the focus and could not get it back: the screen changed under it (docs/screen-focus.md).
        out.push_str(&format!(
            "            if (!__cui_focus_restore(root, __focus) && __focus) {{ __cui_screen(root, true, {}, __cui_screen_of); }}\n",
            routed
        ));
    }
    out.push_str("        }\n");

    out.push_str("        __render();\n");

    // docs/schedules.md: `start` runs after the first render, in the order written; `every` arms its timer.
    for s in &c.schedules {
        match s.kind {
            IrScheduleKind::Start => {
                out.push_str(&format!("        __on_{}();\n", s.event));
            }
            // docs/routing.md section 4: the route event hears the path the page loaded at, and every later change of the
            // fragment to a route (from the event's `newURL`, so two changes in one task are two paths).
            IrScheduleKind::Route => {
                // After a change of the fragment the handler finishes, then the focus moves to the new screen's heading and the title
                // follows; at mount only the title is set (docs/screen-focus.md section 3).
                out.push_str(&format!(
                    "        function __cui_hash(e) {{ const p = __cui_route_of(e.newURL); if (p !== null) {{ Promise.resolve(__on_{0}(p)).finally(function () {{ __cui_screen(root, true, true, __cui_screen_of); }}); }} }}\n        window.addEventListener('hashchange', __cui_hash);\n        Promise.resolve(__on_{0}(__cui_route_now())).finally(function () {{ __cui_screen(root, false, true, __cui_screen_of); }});\n",
                    s.event
                ));
            }
            // docs/streams.md: the connection starts after the first render, in the order written; its status events and
            // its messages run the handlers.
            IrScheduleKind::Subscribe => {
                if let Some(t) = &s.stream {
                    let status = match &t.status {
                        Some(h) => format!("function (w) {{ __on_{h}(w); }}"),
                        None => "null".to_string(),
                    };
                    out.push_str(&format!(
                        "        const __cui_stream = __cui_stream_new({{ url: {}, hosts: __cui_net_hosts, cred: __cui_cred, onMessage: function (t) {{ __on_{}(t); }}, onStatus: {status} }});\n        __cui_stream.start();\n",
                        js_string(&t.url),
                        s.event
                    ));
                }
            }
            IrScheduleKind::Every(ms) => {
                out.push_str(&format!(
                    "        __cui_every.push({{ ms: {1}, next: Date.now() + {1}, o: null, run: function () {{ if (__cui_busy.{0} === 0) {{ __on_{0}(); }} }} }});\n",
                    s.event, ms
                ));
            }
        }
    }
    if !ticked.is_empty() {
        // docs/schedules.md section 11.4: a timeout chain that reschedules from `next` (no drift, no burst after a
        // throttled tab), paused while the page is hidden, a catch-up tick on becoming visible.
        for line in [
            "function __cui_arm(s) { s.o = setTimeout(function () { s.o = null; s.next += s.ms; if (s.next <= Date.now()) { s.next = Date.now() + s.ms; } __cui_arm(s); s.run(); }, Math.max(0, s.next - Date.now())); }",
            "function __cui_pause() { __cui_every.forEach(function (s) { if (s.o !== null) { clearTimeout(s.o); s.o = null; } }); }",
            "function __cui_resume() { const now = Date.now(); __cui_every.forEach(function (s) { if (s.o !== null) { return; } if (s.next <= now) { s.next = now + s.ms; __cui_arm(s); s.run(); } else { __cui_arm(s); } }); }",
            "function __cui_visibility() { const a = document.visibilityState !== 'hidden'; if (a === __cui_active) { return; } __cui_active = a; if (a) { __cui_resume(); } else { __cui_pause(); } }",
            "function __cui_pagehide() { if (__cui_active) { __cui_active = false; __cui_pause(); } }",
            "function __cui_pageshow(e) { if (e.persisted) { __cui_visibility(); } }",
            "document.addEventListener('visibilitychange', __cui_visibility);",
            "window.addEventListener('pagehide', __cui_pagehide);",
            "window.addEventListener('pageshow', __cui_pageshow);",
            "if (__cui_active) { __cui_every.forEach(__cui_arm); }",
        ] {
            out.push_str("        ");
            out.push_str(line);
            out.push('\n');
        }
    }

    // docs/streams.md: a hidden page closes the connection and a visible one opens it at once, after the `every` handlers above.
    if c.schedules
        .iter()
        .any(|s| s.kind == IrScheduleKind::Subscribe)
    {
        for line in [
            "function __cui_stream_vis() { if (document.visibilityState === 'hidden') { __cui_stream.pause(); } else { __cui_stream.resume(); } }",
            "function __cui_stream_pagehide() { __cui_stream.pause(); }",
            "function __cui_stream_pageshow(e) { if (e.persisted) { __cui_stream_vis(); } }",
            "document.addEventListener('visibilitychange', __cui_stream_vis);",
            "window.addEventListener('pagehide', __cui_stream_pagehide);",
            "window.addEventListener('pageshow', __cui_stream_pageshow);",
        ] {
            out.push_str("        ");
            out.push_str(line);
            out.push('\n');
        }
    }

    // Tier 15: prop-consuming components return an update handle.
    // The parent re-render moves a slot wrapper (which keeps the
    // child's whole subtree and closures alive) and then calls
    // `__cui_update` with the *dynamic* property values only — a
    // constant property is an initial value for the field, so a
    // parent re-render must not clobber a field the child has
    // changed since mount.
    // Tier 17: awaiting components also return a `__cui_dispose`
    // handle — the pending awaits resolve `{Cancelled}` so the
    // `match`'s `Cancelled` arm dispatches (drop happens for
    // *supersede*, not disposal).
    if returns_handle {
        let mut fields = String::new();
        if takes_props {
            let mut upd = String::new();
            for s in &c.state {
                upd.push_str(&format!(
                    "                if (props.{0} !== undefined) {{ __state_{0} = props.{0}; }}\n",
                    s.name
                ));
            }
            fields.push_str("            __cui_update: function (props) {\n");
            fields.push_str(&upd);
            fields.push_str("                __render();\n");
            fields.push_str("            }");
        }
        if needs_dispose {
            if !fields.is_empty() {
                fields.push_str(",\n");
            }
            fields.push_str("            __cui_dispose: function () {\n");
            if has_instances {
                // Cascade first: the children of a disposed
                // component are disposed too, transitively (the
                // slot table holds every instance this component
                // mounted; For sites hold arrays of slots).
                fields.push_str("                for (const __dk in __cui_slots) {\n");
                fields.push_str("                    const __ds = __cui_slots[__dk];\n");
                fields.push_str("                    if (Array.isArray(__ds)) {\n");
                fields.push_str("                        __ds.forEach(function (x) { if (x.inst) x.inst.__cui_dispose(); });\n");
                fields.push_str("                    } else if (__ds.inst) {\n");
                fields.push_str("                        __ds.inst.__cui_dispose();\n");
                fields.push_str("                    }\n");
                fields.push_str("                }\n");
            }
            if c.schedules.iter().any(|s| s.kind == IrScheduleKind::Route) {
                fields.push_str(
                    "                window.removeEventListener('hashchange', __cui_hash);\n",
                );
            }
            if c.schedules
                .iter()
                .any(|s| s.kind == IrScheduleKind::Subscribe)
            {
                for line in [
                    "__cui_stream.dispose();",
                    "document.removeEventListener('visibilitychange', __cui_stream_vis);",
                    "window.removeEventListener('pagehide', __cui_stream_pagehide);",
                    "window.removeEventListener('pageshow', __cui_stream_pageshow);",
                ] {
                    fields.push_str("                ");
                    fields.push_str(line);
                    fields.push('\n');
                }
            }
            if !ticked.is_empty() {
                for line in [
                    "__cui_every.forEach(function (s) { if (s.o !== null) { clearTimeout(s.o); s.o = null; } });",
                    "__cui_every.length = 0;",
                    "document.removeEventListener('visibilitychange', __cui_visibility);",
                    "window.removeEventListener('pagehide', __cui_pagehide);",
                    "window.removeEventListener('pageshow', __cui_pageshow);",
                ] {
                    fields.push_str("                ");
                    fields.push_str(line);
                    fields.push('\n');
                }
            }
            if has_awaits {
                // Then the instance's own pending requests: their
                // awaits resolve `{Cancelled}` and the awaiting
                // `match` dispatches the arm.
                fields.push_str("                for (const g in __cui_inflight) {\n");
                fields.push_str("                    const t = __cui_inflight[g];\n");
                fields.push_str(
                    "                    if (t) { t.disposed = true; __cui_inflight[g] = null; if (t.abort) { t.abort(); } }\n",
                );
                fields.push_str("                }\n");
            }
            fields.push_str("            }");
        }
        out.push_str("        return {\n");
        out.push_str(&fields);
        out.push_str("\n        };\n");
    }
    out.push_str("    })();\n");
    out.push_str("}\n");
    out
}

/// One statement of a handler, at `indent`. `snap` is the list of fields the handler snapshots when it is atomic: a leaf that
/// awaits clears the snapshot while it runs and takes it again after, at any depth (docs/handler-sequences.md section 5). An
/// `if` is a JavaScript `if`; its condition is pure, so only a leaf in a branch can await.
fn emit_stmt(
    out: &mut String,
    s: &IrStmt,
    params: &[&str],
    snap: Option<&str>,
    indent: &str,
    paint: bool,
) {
    match s {
        IrStmt::If {
            cond, then, else_, ..
        } => {
            out.push_str(&format!(
                "{indent}if ({}) {{\n",
                emit_expr_runtime(cond, params)
            ));
            let inner = format!("{indent}    ");
            for t in then {
                emit_stmt(out, t, params, snap, &inner, true);
            }
            if else_.is_empty() {
                out.push_str(&format!("{indent}}}\n"));
            } else {
                out.push_str(&format!("{indent}}} else {{\n"));
                for t in else_ {
                    emit_stmt(out, t, params, snap, &inner, true);
                }
                out.push_str(&format!("{indent}}}\n"));
            }
        }
        leaf => {
            let suspends = body_uses_await(leaf);
            if suspends && paint {
                out.push_str(&format!("{indent}__render();\n"));
            }
            let awaits = snap.is_some() && suspends;
            if awaits {
                out.push_str(&format!("{indent}__snap = null;\n"));
            }
            let text = match leaf {
                IrStmt::Assign { target, value, .. } => {
                    STATE_PREFIX.to_string()
                        + target
                        + " = "
                        + &emit_expr_runtime(value, params)
                        + ";"
                }
                IrStmt::Expr { expr, .. } => emit_expr_runtime(expr, params) + ";",
                IrStmt::If { .. } => String::new(),
            };
            out.push_str(&format!("{indent}{text}\n"));
            if let (true, Some(list)) = (awaits, snap) {
                out.push_str(&format!("{indent}__snap = [{list}];\n"));
            }
        }
    }
}

pub(crate) fn js_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            // Section 9.2: the module is ASCII. Everything else is a \u escape, one per UTF-16 unit.
            c if (' '..='~').contains(&c) => out.push(c),
            c => {
                let mut units = [0u16; 2];
                for u in c.encode_utf16(&mut units) {
                    out.push_str(&format!("\\u{u:04x}"));
                }
            }
        }
    }
    out.push('"');
    out
}

