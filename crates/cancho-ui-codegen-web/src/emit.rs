//! The web backend's emitter. `emit_module` produces a JavaScript
//! source string from a lowered `IrFile`. The shape is a single
//! ES module with one `mount()` function per component and one
//! `mount_<ComponentName>(root)` export.
//!
//! The emitted code uses only browser-native APIs
//! (`document.createElement`, `document.createTextNode`,
//! `Element.appendChild`, `Element.setAttribute`) — no third-party
//! runtime, no transpilation needed. The `cui-col` / `cui-row`
//! layout classes require the minimal stylesheet in
//! `examples/hello/hello.css` (Phase 2 moves this into a built-in
//! asset).
//!
//! The generated code is the *target* of the source map. Phase 2
//! emits the source map; Phase 1 emits a fixed comment that names
//! the source file.

use cancho_ui_ir::ir::*;

pub fn module_for_file(ir: &IrFile) -> String {
    emit_module(ir, None)
}

/// `source_name` is the cancho-ui source file path, used in the
/// generated header comment. `None` for tests.
pub fn emit_module(ir: &IrFile, source_name: Option<&str>) -> String {
    let mut out = String::new();
    out.push_str("// Generated by cancho-ui build (Phase 1, web backend).\n");
    if let Some(name) = source_name {
        out.push_str(&format!("// Source: {}\n", name));
    }
    out.push_str("// Schema: ");
    out.push_str(&ir.schema);
    out.push(' ');
    out.push_str(&ir.version);
    out.push('\n');
    out.push_str("//\n");
    out.push_str("// Do not edit by hand. Re-run `cancho-ui build` to regenerate.\n");
    out.push('\n');

    for c in &ir.components {
        out.push_str(&emit_component(c));
        out.push('\n');
    }

    // The entry point: mount the last-declared component to
    // `#root` when the script is loaded as a module. Phase 2 will
    // take an explicit `--entry <name>` flag.
    if let Some(last) = ir.components.last() {
        out.push_str(&format!(
            "const root = (typeof document !== 'undefined') ? document.getElementById('root') : null;\n"
        ));
        out.push_str(&format!(
            "if (root) {{ mount_{name}(root); }}\n",
            name = last.name
        ));
        out.push_str(&format!(
            "export {{ mount_{name} }};\n",
            name = last.name
        ));
    } else {
        out.push_str("// (no components in source)\n");
    }

    out
}

fn emit_component(c: &IrComponent) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "// Component: {name} (id {id})\n",
        name = c.name,
        id = c.id.0
    ));
    out.push_str(&format!(
        "function mount_{name}(root) {{\n",
        name = c.name
    ));
    out.push_str(&emit_view_node("    ", &c.view.body));
    out.push_str("    root.appendChild(__el);\n");
    out.push_str("    return __el;\n");
    out.push_str("}\n");
    out
}

fn emit_view_node(indent: &str, node: &IrViewNode) -> String {
    match node {
        IrViewNode::Text { value, .. } => {
            format!(
                "{indent}const __el = document.createElement('span');\n\
                 {indent}__el.appendChild(document.createTextNode({literal}));\n",
                indent = indent,
                literal = js_string(value),
            )
        }
        IrViewNode::Element { kind, accessibility, children, .. } => {
            let tag = kind.tag_name();
            let mut out = format!(
                "{indent}const __el = document.createElement('{tag}');\n",
                indent = indent,
                tag = tag,
            );
            if let Some(cls) = kind.layout_class() {
                out.push_str(&format!(
                    "{indent}__el.classList.add('{cls}');\n",
                    indent = indent,
                    cls = cls,
                ));
            }
            if let Some(role) = &accessibility.role {
                let role_attr = match role {
                    IrRole::Text => "text",
                    IrRole::Other(s) => s.as_str(),
                };
                out.push_str(&format!(
                    "{indent}__el.setAttribute('role', {literal});\n",
                    indent = indent,
                    literal = js_string(role_attr),
                ));
            }
            if let Some(label) = &accessibility.label {
                out.push_str(&format!(
                    "{indent}__el.setAttribute('aria-label', {literal});\n",
                    indent = indent,
                    literal = js_string(label),
                ));
            }
            for c in children {
                out.push_str(&emit_view_node_child(indent, c));
            }
            out
        }
    }
}

fn emit_view_node_child(indent: &str, node: &IrViewNode) -> String {
    match node {
        IrViewNode::Text { value, .. } => {
            format!(
                "{indent}__el.appendChild(document.createTextNode({literal}));\n",
                indent = indent,
                literal = js_string(value),
            )
        }
        IrViewNode::Element { .. } => {
            let mut out = String::new();
            out.push_str(indent);
            out.push_str("{\n");
            // Child elements get their own scope to avoid
            // colliding with the parent's `__el`.
            out.push_str(&emit_view_node_inner(indent, "    ", node));
            out.push_str(indent);
            out.push_str("}\n");
            out
        }
    }
}

fn emit_view_node_inner(parent_indent: &str, extra: &str, node: &IrViewNode) -> String {
    match node {
        IrViewNode::Text { value, .. } => {
            format!(
                "{parent}{extra}const __child = document.createElement('span');\n\
                 {parent}{extra}__child.appendChild(document.createTextNode({literal}));\n\
                 {parent}{extra}__el.appendChild(__child);\n",
                parent = parent_indent,
                extra = extra,
                literal = js_string(value),
            )
        }
        IrViewNode::Element { kind, accessibility, children, .. } => {
            let tag = kind.tag_name();
            let mut out = format!(
                "{parent}{extra}const __child = document.createElement('{tag}');\n",
                parent = parent_indent,
                extra = extra,
                tag = tag,
            );
            if let Some(cls) = kind.layout_class() {
                out.push_str(&format!(
                    "{parent}{extra}__child.classList.add('{cls}');\n",
                    parent = parent_indent,
                    extra = extra,
                    cls = cls,
                ));
            }
            if let Some(role) = &accessibility.role {
                let role_attr = match role {
                    IrRole::Text => "text",
                    IrRole::Other(s) => s.as_str(),
                };
                out.push_str(&format!(
                    "{parent}{extra}__child.setAttribute('role', {literal});\n",
                    parent = parent_indent,
                    extra = extra,
                    literal = js_string(role_attr),
                ));
            }
            if let Some(label) = &accessibility.label {
                out.push_str(&format!(
                    "{parent}{extra}__child.setAttribute('aria-label', {literal});\n",
                    parent = parent_indent,
                    extra = extra,
                    literal = js_string(label),
                ));
            }
            let deeper = format!("{}{}", parent_indent, extra);
            for c in children {
                match c {
                    IrViewNode::Text { value, .. } => {
                        out.push_str(&format!(
                            "{deeper}__child.appendChild(document.createTextNode({literal}));\n",
                            deeper = deeper,
                            literal = js_string(value),
                        ));
                    }
                    IrViewNode::Element { .. } => {
                        out.push_str(&format!("{deeper}{{\n"));
                        out.push_str(&emit_view_node_inner(&deeper, "    ", c));
                        out.push_str(&format!("{deeper}}}\n"));
                    }
                }
            }
            out.push_str(&format!(
                "{parent}{extra}__el.appendChild(__child);\n",
                parent = parent_indent,
                extra = extra,
            ));
            out
        }
    }
}

fn js_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emits_a_text_element() {
        let lit = js_string("hello, world");
        assert_eq!(lit, r#""hello, world""#);
        assert_eq!(js_string("with \"quote\""), r#""with \"quote\"""#);
        assert_eq!(js_string("line\nbreak"), r#""line\nbreak""#);
    }
}