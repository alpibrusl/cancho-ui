#[test]
fn requires_decl_emitted_in_ir() {
    // `requires Clock;` with a corresponding `clock.now()` use
    // passes Tier 4's capability check; the JS keeps the
    // platform-adapter stub for `Clock`.
    let src = "\
component Ticker {
    requires Clock;
    state n: Int = 0;
    on Tick { n = clock.now(); }
    view { Text { \"hi\" } }
}
";
    let js = compile_str(src);
    assert!(js.contains("function mount_Ticker"));
    assert!(js.contains("__cui_clock_now()"));
    assert!(js.contains("__state_n = __cui_clock_now();"));
    assert!(js.contains("function __cui_clock_now()"));
    assert!(js.contains("Date.now()"));
}

