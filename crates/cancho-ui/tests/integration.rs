//! Integration tests for the cancho-ui CLI pipeline.
//!
//! Each test compiles a cancho-ui source string through the full
//! pipeline (lex → parse → type-check → IR lowering → JS emit)
//! and asserts the JS output. Snapshot tests pin the exact emitted
//! bytes; the fixtures double as the example programs.

use cancho_ui_codegen_web::emit_module;
use cancho_ui_ir::lower_file;
use cancho_ui_syntax::parser::parse;
use cancho_ui_syntax::lexer::lex;
use cancho_ui_types::check_file;

fn compile_str(src: &str) -> String {
    let toks = lex(src).expect("lex");
    let ast = parse(toks).expect("parse");
    check_file(&ast).expect("check");
    let ir = lower_file(&ast).expect("lower");
    emit_module(&ir, Some("<test>"))
}

#[test]
fn hello_world_emits_expected_js() {
    let src = "\
component Hello {
    view {
        Column {
            role: banner
            label: \"hello banner\"
            Text {
                role: heading
                \"hello, world\"
            }
        }
    }
}
";
    let js = compile_str(src);
    // The header is stable.
    assert!(js.starts_with("// Generated by cancho-ui build (Tier 4, web backend).\n"));
    assert!(js.contains("// Source: <test>\n"));
    assert!(js.contains("// Schema: cancho-ui-ir 0.1.0\n"));

    // The mount function is present.
    assert!(js.contains("function mount_Hello(root)"));
    assert!(js.contains("mount_Hello(root);"));

    // The Column primitive becomes a div with the layout class.
    assert!(js.contains("document.createElement('div')"));
    assert!(js.contains("classList.add('cui-col')"));

    // Accessibility metadata is honored.
    assert!(js.contains("setAttribute('role', \"banner\")"));
    assert!(js.contains("setAttribute('aria-label', \"hello banner\")"));

    // The Text primitive becomes a span.
    assert!(js.contains("document.createElement('span')"));
    assert!(js.contains("setAttribute('role', \"heading\")"));
    assert!(js.contains("document.createTextNode(\"hello, world\")"));

    // The mounting point is at #root.
    assert!(js.contains("document.getElementById('root')"));

    // The mount function is exported.
    assert!(js.contains("export { mount_Hello };"));
}

