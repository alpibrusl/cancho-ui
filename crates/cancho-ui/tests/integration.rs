#[test]
fn diagnostic_format_is_stable() {
    use cancho_ui_types::{check_file as cf, CheckError, TypeError};
    use cancho_ui_syntax::parser::parse as p;
    use cancho_ui_syntax::lexer::lex as l;

    // Lowercase component name → type-not-pascal-case.
    let src = "component hello { view { Text { \"hi\" } } }\n";
    let toks = l(src).unwrap();
    let ast = p(toks).unwrap();
    let err = cf(&ast).unwrap_err();
    assert!(matches!(
        err,
        cancho_ui_types::CheckError::Shape(TypeError::NotPascalCase { .. })
    ));
}

#[test]
fn counter_compiles_and_emits_reactive_js() {
    // The Tier 2 Counter: state, event handler, the Button primitive,
    // and reactive re-render. The emitted JS is checked structurally
    // here; an end-to-end DOM test lives in /tmp/test-counter.js
    // (run manually with jsdom).
    let src = "\
component Counter {
    state count: Int = 0;
    on Increment { count = count + 1; }
    on Reset { count = 0; }
    view {
        Column {
            Text { role: status \"Count: {count}\" }
            Button { label: \"Increment\" on: Increment }
            Button { label: \"Reset\" on: Reset }
        }
    }
}
";
    let js = compile_str(src);

    // State initialization.
    assert!(js.contains("let __state_count = 0;"));
    // Event handlers.
    assert!(js.contains("function __on_Increment()"));
    assert!(js.contains("function __on_Reset()"));
    assert!(js.contains("__state_count = (__state_count + 1);"));
    assert!(js.contains("__state_count = 0;"));
    // Re-render wiring.
    assert!(js.contains("__render();"));
    assert!(js.contains("function __render()"));
    assert!(js.contains("root.textContent = ''"));
    // State interpolation reads through __state_count.
    assert!(js.contains("String(__state_count)"));
    // DOM event wiring.
    assert!(js.contains("addEventListener('click', __on_Increment)"));
    assert!(js.contains("addEventListener('click', __on_Reset)"));
}

#[test]
