#[test]
fn await_and_request_type_are_recognised() {
    // Tier 7: `Request[T]` is a generic type, `await(expr)` is an
    // expression, and `sleep(ms)` is a pure-runtime builtin that
    // needs no declared capability. Event handlers are generated
    // as `async function` so the `await` suspends properly.
    let src = "\
component Ticker {
    state status: String = \"Idle\";
    state r: Result[Int, String] = Ok(0);
    on Tick {
        status = \"Waiting\";
        r = await(sleep(50));
        status = match r {
            Ok(v) => { \"Ok\" }
            Err(e) => { \"Err\" }
            Cancelled => { \"Cancelled\" }
        };
    }
    view {
        Text {
            role: status
            \"Status: {status}\"
        }
    }
}
";
    let js = compile_str(src);
    // Handlers are async so `await` can suspend.
    assert!(js.contains("async function __on_Tick"));
    // `await(sleep(50))` is lowered to the cancellation-tracked
    // runtime call (Tier 10): the `sleep_ms` group cancels a
    // still-pending previous request.
    assert!(js.contains(
        "await __cui_call(\"sleep\", function () { return __cui_sleep_ms(50); }, __cui_inflight)"
    ));
    assert!(js.contains("const __cui_inflight = { };"));
    // The sleep adapter is emitted when the body uses sleep.
    assert!(js.contains("function __cui_sleep_ms(ms)"));
    // The `__cui_cancelled` sentinel is thrown when a superseded
    // request resolves, and the handler's try/catch swallows it.
    assert!(js.contains("const __cui_cancelled = Symbol"));
    // This handler writes more than once, so the catch also puts back what the segment wrote and redraws before it
    // rethrows (docs/semantics.md, "A handler that faults"); the sentinel itself is still swallowed.
    assert!(js.contains("if (e !== __cui_cancelled) {"));
    assert!(js.contains("if (__snap) { [__state_status, __state_r] = __snap; }"));
    // `Cancelled` is a unit-variant pattern: tag test, no payload.
    assert!(js.contains("__cui_tag === \"Cancelled\""));
}

