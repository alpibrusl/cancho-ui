#[test]
fn textfield_with_event_handler_passes_param() {
    // Tier 5: `on: Change(value)` declares a parameter; the JS
    // emitter passes `e.target.value` to the handler so the body
    // sees the new value as a bare identifier, not a state field.
    let src = "\
component T {
    state q: String = \"\";
    on Change(value) { q = value; }
    view { TextField { value: q on: Change } }
}
";
    let js = compile_str(src);
    assert!(js.contains("function __on_Change(value)"));
    assert!(js.contains("__state_q = value;"));
    assert!(js.contains("addEventListener('input', function (e) { __on_Change(e.target.value); })"));
}

#[test]
fn searchable_list_compiles_with_textfield_and_clock() {
    // Tier 5: the proposal §9.3 searchable-list demo, Tier 5
    // synchronous form. TextField drives a query state field,
    // an event handler updates it, and the Clock capability
    // records the time of the last input.
    let src = "\
component Search {
    requires Clock;
    state query: String = \"\";
    state last_searched: Int = 0;
    on Change(value) { query = value; last_searched = clock.now(); }
    view {
        Column {
            TextField { value: query on: Change }
            Text { role: status \"Searching for: {query}\" }
        }
    }
}
";
    let js = compile_str(src);
    assert!(js.contains("function mount_Search"));
    assert!(js.contains("__on_Change(value)"));
    assert!(js.contains("__state_query = value;"));
    assert!(js.contains("__state_last_searched = __cui_clock_now();"));
    assert!(js.contains("String(__state_query)"));
    assert!(js.contains("addEventListener('input'"));
}

#[test]
fn match_emits_nested_ternaries_with_tag_dispatch() {
    // Tier 6: a match on a `Result[Int, String]` is lowered to
    // nested ternaries that dispatch on the `__cui_tag` runtime
    // tag. Each arm body sees its bound name as a bare
    // identifier (the body's local scope binds it).
    let src = "\
component Half {
    state result: Result[Int, String] = Ok(0);
    on Set(n) { result = Ok(n); }
    on Fail { result = Err(\"bad\"); }
    view {
        Text {
            match result {
                Ok(v) => { \"value: ok\" }
                Err(e) => { \"value: bad\" }
            }
        }
    }
}
";
    let js = compile_str(src);
    // Initial value: Ok(0).
    assert!(js.contains("({__cui_tag:\"Ok\",value:0})"));
    // Event handlers construct the right tag.
    assert!(js.contains("({__cui_tag:\"Ok\",value:n})"));
    assert!(js.contains("({__cui_tag:\"Err\",reason:\"bad\"})"));
    // Match dispatch on the tag.
    assert!(js.contains("__cui_tag === \"Ok\""));
    assert!(js.contains("__cui_tag === \"Err\""));
    // Bindings become local var in IIFEs.
    assert!(js.contains("var v = __cui_match_"));
    assert!(js.contains("var e = __cui_match_"));
}

#[test]
fn match_supports_constructor_wildcard_and_ident_patterns() {
    // Tier 6: three pattern shapes:
    //   - `Ok(v)` (constructor + binding),
    //   - `_`     (wildcard),
    //   - `name`  (binds the whole value).
    let src = "\
component T {
    state x: Result[Int, String] = Ok(0);
    view {
        Text {
            match x {
                Ok(v) => { v }
                _ => { 0 }
            }
        }
    }
}
";
    let js = compile_str(src);
    assert!(js.contains("var v = __cui_match_"));
    // The wildcard arm body is the literal 0.
    assert!(js.contains("? 0 :"));
}

