//! Integration tests for the cancho-ui CLI pipeline.
//!
//! Each test compiles a cancho-ui source string through the full
//! pipeline (lex → parse → type-check → IR lowering → JS emit)
//! and asserts the JS output. Snapshot tests pin the exact emitted
//! bytes; the fixtures double as the example programs.

use cancho_ui_codegen_web::emit_module;
use cancho_ui_ir::lower_file;
use cancho_ui_syntax::parser::parse;
use cancho_ui_syntax::lexer::lex;
use cancho_ui_types::check_file;

fn compile_str(src: &str) -> String {
    let toks = lex(src).expect("lex");
    let ast = parse(toks).expect("parse");
    check_file(&ast).expect("check");
    let ir = lower_file(&ast).expect("lower");
    emit_module(&ir, Some("<test>"))
}

#[test]
fn hello_world_emits_expected_js() {
    let src = "\
component Hello {
    view {
        Column {
            role: banner
            label: \"hello banner\"
            Text {
                role: heading
                \"hello, world\"
            }
        }
    }
}
";
    let js = compile_str(src);
    // The header is stable.
    assert!(js.starts_with("// Generated by cancho-ui build (Phase 1, web backend).\n"));
    assert!(js.contains("// Source: <test>\n"));
    assert!(js.contains("// Schema: cancho-ui-ir 0.1.0\n"));

    // The mount function is present.
    assert!(js.contains("function mount_Hello(root)"));
    assert!(js.contains("mount_Hello(root);"));

    // The Column primitive becomes a div with the layout class.
    assert!(js.contains("document.createElement('div')"));
    assert!(js.contains("__el.classList.add('cui-col')"));

    // Accessibility metadata is honored.
    assert!(js.contains("__el.setAttribute('role', \"banner\")"));
    assert!(js.contains("__el.setAttribute('aria-label', \"hello banner\")"));

    // The Text primitive becomes a span.
    assert!(js.contains("document.createElement('span')"));
    assert!(js.contains("__child.setAttribute('role', \"heading\")"));
    assert!(js.contains("document.createTextNode(\"hello, world\")"));

    // The mounting point is at #root.
    assert!(js.contains("document.getElementById('root')"));

    // The mount function is exported.
    assert!(js.contains("export { mount_Hello };"));
}

#[test]
fn row_uses_row_layout_class() {
    let src = "\
component Bar {
    view {
        Row { Text { \"left\" } Text { \"right\" } }
    }
}
";
    let js = compile_str(src);
    assert!(js.contains("classList.add('cui-row')"));
}

#[test]
fn empty_text_node_compiles() {
    // A Text primitive with no body and no metadata still renders
    // an empty span. This is the path for `Text { }`.
    let src = "\
component Empty {
    view {
        Text { }
    }
}
";
    let js = compile_str(src);
    assert!(js.contains("function mount_Empty"));
    assert!(js.contains("document.createElement('span')"));
}

#[test]
fn user_named_component_lowers_to_named_kind() {
    let src = "\
component Card {
    view { Text { \"body\" } }
}

component Page {
    view { Card { } }
}
";
    let js = compile_str(src);
    // Both components emit mount functions; the page mounts the
    // last-declared component by default.
    assert!(js.contains("function mount_Card"));
    assert!(js.contains("function mount_Page"));
}

#[test]
fn diagnostic_format_is_stable() {
    use cancho_ui_types::check_file as cf;
    use cancho_ui_syntax::parser::parse as p;
    use cancho_ui_syntax::lexer::lex as l;

    // Lowercase component name → type-not-pascal-case.
    let src = "component hello { view { Text { \"hi\" } } }\n";
    let toks = l(src).unwrap();
    let ast = p(toks).unwrap();
    let err = cf(&ast).unwrap_err();
    assert!(matches!(
        err,
        cancho_ui_types::TypeError::NotPascalCase { .. }
    ));
}